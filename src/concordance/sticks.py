"""STICKS AS DATA — the catalog of tick sticks and the one loader that runs one (issue #13, 2026-10-17).

A tick stick (tickstick.py; docs/TICK_STICK.md) is an open question with sealed and cited marks on it. Most
sticks are DATA: a few numeric seals, a stick, a list of marks — prose and literals, nothing computed. They
live here as data/sticks/<name>.json (tracked: they are SOURCE, not keeping) and tools/tick.py runs them
through `run`. The computational minority (the Riemann/BSD/Robin families, anything that calls
verify_derivation itself) stays Python in tools/tick.py and is registered in the SAME catalog as a HANDLER
entry, so the CLI has one table and one resolver.

A DATA entry:

    {"schema": 1,
     "name": "zeta",                              # the entry id — the file stem
     "aliases": ["zeta", "riemann_zeta", ...],    # CLI names. Unique across the catalog: a duplicate alias
                                                  # is a LOAD-TIME error (never a silent first-match)
     "doc": "...",                                # the reader's note (was the function's docstring)
     "seals": [                                   # minted first, in order; each must HOLD or the run aborts (rc 1)
       {"key": "basel_zeta_2", "nid": "basel_zeta_2", "expr": "3.141592653589793**2 / 6",
        "value": 1.6449340668482264, "tol": 1e-12, "domain": "mathematics"},          # a numeric derivation
       {"key": "compound", "domain": "economics", "artifact": "ECON_VERIFY", "spec": {...}}  # a domain verifier
     ],
     "sticks": [                                  # then each stick: create (idempotent), mint its marks in order
       {"question": "The zeta function", "statement": "...", "field": "meta", "references": ["..."],
        "by": "Narrow Highway - the zeta function, 2026-10-07",
        "marks": [{"kind": "witness", "claim": "...", "seal": "basel_zeta_2"},    # seal = a key from `seals`
                  {"kind": "postulate", "claim": "...", "source": "..."},
                  {"kind": "bound", "claim": "...", "seal": "k", "up_to": 100, "unit": "height T"},
                  {"kind": "note", "claim": "..."}]}
     ]}

A HANDLER entry:

    {"schema": 1, "name": "riemann", "aliases": ["riemann"], "handler": "riemann",
     "params": [{"type": "float", "default": 100.0}], "why_python": "calls verify_derivation itself (1x)"}

`handler` names a function in tools/tick.py; `params` are the CLI arguments main() parses for it, in order.

The seal path is exactly the verify door's (verify_derivation -> receipts.attach -> CAS + ledger), so every
seal is a real, re-checkable entry in this node's keeping; a mark is minted through `mint_marks`, idempotent
and seal-or-claim guarded. The data files were generated by REPLAYING the former functions through
instrumented helpers (tools/tick_record.py) and are pinned byte-identical to them by tools/tick_golden.py.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Dict, Iterator, List, Optional

SCHEMA = 1
_ROOT = Path(__file__).resolve().parents[2]
PARAM_TYPES = {"int": int, "float": float, "str": str}
_MARK_KEYS = {"kind", "claim", "seal", "source", "up_to", "unit"}


class StickError(ValueError):
    """A catalog that cannot be trusted: a duplicate alias, a malformed entry, a seal key nothing minted."""


def catalog_dir() -> Path:
    env = os.environ.get("CONCORDANCE_STICKS_DIR", "").strip()
    return Path(env) if env else _ROOT / "data" / "sticks"


# ── the catalog ─────────────────────────────────────────────────────────────────────────────────
class Catalog:
    """Every entry by name, every alias resolved to exactly one entry."""

    def __init__(self, entries: Dict[str, Dict[str, Any]], aliases: Dict[str, str], path: Path):
        self.entries = entries
        self.aliases = aliases
        self.path = path

    def __iter__(self) -> Iterator[Dict[str, Any]]:
        return iter(self.entries.values())

    def __len__(self) -> int:
        return len(self.entries)

    def resolve(self, name: str) -> Optional[Dict[str, Any]]:
        """An alias first (the table the CLI has always had), then an entry's own name."""
        key = (name or "").strip()
        owner = self.aliases.get(key)
        if owner is not None:
            return self.entries[owner]
        return self.entries.get(key)


def _require(cond: bool, where: str, msg: str) -> None:
    if not cond:
        raise StickError(f"{where}: {msg}")


def validate_entry(entry: Dict[str, Any], where: str = "entry") -> None:
    """Structural validation — the shape the loader needs. Semantics (a sealed kind needs a HOLDS seal,
    a cited kind needs a source) are tickstick.tick's to refuse at mint time, as they always were."""
    _require(isinstance(entry, dict), where, "not an object")
    _require(entry.get("schema") == SCHEMA, where, f"schema must be {SCHEMA}")
    name = entry.get("name")
    _require(isinstance(name, str) and name.strip() and name == name.strip(), where, "name must be a non-empty string")
    aliases = entry.get("aliases")
    _require(isinstance(aliases, list) and all(isinstance(a, str) and a.strip() for a in aliases), where,
             "aliases must be a list of non-empty strings")
    _require(len(set(aliases)) == len(aliases), where, "an alias is repeated inside the entry")
    if "handler" in entry:
        _require(isinstance(entry["handler"], str) and entry["handler"].strip(), where, "handler must name a function")
        for i, p in enumerate(entry.get("params", []) or []):
            _require(isinstance(p, dict) and p.get("type") in PARAM_TYPES and "default" in p, where,
                     f"params[{i}] needs type (int|float|str) and default")
        _require("seals" not in entry and "sticks" not in entry, where, "a handler entry carries no seals/sticks")
        return
    seals = entry.get("seals", [])
    _require(isinstance(seals, list), where, "seals must be a list")
    keys = set()
    for i, s in enumerate(seals):
        w = f"{where}.seals[{i}]"
        _require(isinstance(s, dict) and isinstance(s.get("key"), str) and s["key"], w, "needs a string key")
        _require(s["key"] not in keys, w, f"seal key {s['key']!r} is repeated")
        keys.add(s["key"])
        _require(isinstance(s.get("domain"), str) and s["domain"], w, "needs a domain")
        if "expr" in s:
            _require(isinstance(s.get("nid"), str) and s["nid"], w, "a numeric seal needs nid")
            _require(isinstance(s["expr"], str) and s["expr"], w, "expr must be a string")
            _require(isinstance(s.get("value"), (int, float)) and not isinstance(s["value"], bool), w,
                     "value must be a number")
            _require(isinstance(s.get("tol"), (int, float)) and not isinstance(s["tol"], bool), w, "tol must be a number")
        else:
            _require(isinstance(s.get("artifact"), str) and s["artifact"], w, "a verifier seal needs artifact")
            _require(isinstance(s.get("spec"), dict), w, "spec must be an object")
    sticks = entry.get("sticks")
    _require(isinstance(sticks, list) and sticks, where, "sticks must be a non-empty list")
    for i, st in enumerate(sticks):
        w = f"{where}.sticks[{i}]"
        _require(isinstance(st, dict) and isinstance(st.get("question"), str) and len(st["question"].strip()) >= 8, w,
                 "needs a question (8+ characters)")
        for k in ("statement", "field", "by"):
            _require(isinstance(st.get(k, ""), str), w, f"{k} must be a string")
        _require(isinstance(st.get("references", []), list), w, "references must be a list")
        marks = st.get("marks", [])
        _require(isinstance(marks, list), w, "marks must be a list")
        if marks:
            _require(isinstance(st.get("by"), str) and st["by"], w, "a stick with marks needs `by`")
        for j, m in enumerate(marks):
            mw = f"{w}.marks[{j}]"
            _require(isinstance(m, dict) and not (set(m) - _MARK_KEYS), mw, f"keys must be among {sorted(_MARK_KEYS)}")
            _require(isinstance(m.get("kind"), str) and isinstance(m.get("claim"), str), mw, "needs kind and claim")
            if "seal" in m:
                _require(m["seal"] in keys, mw, f"seal {m['seal']!r} names no key in seals")
            if "source" in m:
                _require(isinstance(m["source"], str), mw, "source must be a string")
            if "unit" in m:
                _require(isinstance(m["unit"], str), mw, "unit must be a string")
            if "up_to" in m:
                _require(isinstance(m["up_to"], (int, float)) and not isinstance(m["up_to"], bool), mw, "up_to must be a number")


def load_catalog(path: Optional[Path] = None) -> Catalog:
    """Read every data/sticks/*.json, validate it, and build the alias table. An alias claimed by two entries,
    a file whose name is not its entry's name, or a malformed entry raises StickError — at load, loud."""
    base = Path(path) if path else catalog_dir()
    _require(base.is_dir(), str(base), "no such catalog directory")
    entries: Dict[str, Dict[str, Any]] = {}
    aliases: Dict[str, str] = {}
    for p in sorted(base.glob("*.json")):
        try:
            entry = json.loads(p.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise StickError(f"{p.name}: not JSON ({exc})") from None
        validate_entry(entry, p.name)
        name = entry["name"]
        _require(p.stem == name, p.name, f"file name must be the entry name ({name!r})")
        _require(name not in entries, p.name, f"entry {name!r} is defined twice")
        entries[name] = entry
        for al in entry["aliases"]:
            other = aliases.get(al)
            _require(other is None, p.name, f"alias {al!r} is already claimed by {other!r} — an alias reaches ONE stick")
            aliases[al] = name
    return Catalog(entries, aliases, base)


# ── the seal path (the verify door's) ────────────────────────────────────────────────────────────
def seal_numeric(nid: str, expr: str, val: Any, domain: str = "mathematics", tol: float = 1e-9) -> Optional[str]:
    """Verify a numeric derivation and return its content hash — the shared seal helper of the Riemann arc."""
    from . import receipts
    from .derivation import verify_derivation
    from .engine import EngineConfig
    r = verify_derivation([{"id": nid, "domain": domain,
          "spec": {"mode": "numeric", "params": {"numeric_expr": expr, "claimed_value": val, "rel_tol": tol}}}])
    if r.get("verdict") != "HOLDS":
        print("  %s did not verify: %s" % (nid, json.dumps(r)[:300])); return None
    r = receipts.attach(r, config=EngineConfig(), domain=domain)
    return (r.get("seal") or {}).get("content_hash")


def seal_verifier(domain: str, artifact_key: str, spec: Dict[str, Any]) -> Optional[str]:
    """Verify a claim through an existing domain verifier and return its seal (verify -> receipts.attach)."""
    from . import receipts
    from .derivation import verify_derivation
    from .engine import EngineConfig
    res = verify_derivation([{"id": "x", "domain": domain, "spec": {artifact_key: spec}}])
    if res.get("verdict") != "HOLDS":
        print("  did NOT hold:", domain, res.get("verdict")); return None
    res = receipts.attach(res, config=EngineConfig(), domain=domain)
    return (res.get("seal") or {}).get("content_hash")


def seal(s: Dict[str, Any]) -> Optional[str]:
    """One catalog seal -> its content hash (None when it did not HOLD)."""
    if "expr" in s:
        return seal_numeric(s["nid"], s["expr"], s["value"], s.get("domain", "mathematics"), s.get("tol", 1e-9))
    return seal_verifier(s["domain"], s["artifact"], s["spec"])


# ── the mint loop ────────────────────────────────────────────────────────────────────────────────
def mint_marks(sid: str, marks: List[Any], by: str) -> int:
    """Shared mint loop - every stick mints through it (2026-10-08: the 25 inline copies and the two kw-dict
    loops were folded in; alpha() had no duplicate guard at all). A mark is (kind, claim, seal) or (kind, claim,
    kw-dict with seal= and/or source=). Idempotent, seal-or-claim guarded. A mark already kept in full is skipped. One kept CUT at
    an older cap - its stored text a strict prefix of the mark (2026-10-08: the cap was 600; 45 kept marks, mostly
    the guard notes, were stored mid-sentence) - is ticked again in full, and the reader supersedes the cut copy
    (tickstick._collapse). A sealed mark whose wording changed but whose seal is kept stays as kept: the seal governs."""
    from . import tickstick as TS
    cap = getattr(TS, "CLAIM_CAP", 600)
    ticks = TS.read(sid).get("ticks", [])
    added = 0
    for kind, claim, *rest in marks:
        extra = rest[0] if rest else None
        kw = dict(extra) if isinstance(extra, dict) else (dict(seal=extra) if extra else {})
        sealv = kw.get("seal")
        want = (claim or "").strip()[:cap]
        same = [t for t in ticks if t.get("kind") == kind and (t.get("seal") or "") == (sealv or "")]
        whole = any((t.get("claim") or "") == want for t in same)
        cut = any(len(want) > len(t.get("claim") or "") and want.startswith(t.get("claim") or "") for t in same)
        if whole or (sealv and same and not cut):
            print("  (already) " + kind); continue
        if cut:
            print("  (superseding a cut copy) " + kind)
        res = TS.tick(sid, kind, claim, by=by, **kw)
        if res.get("ok"):
            added += 1; print("  " + kind)
        else:
            print("  REFUSED " + kind + ": " + res.get("error", ""))
    f = TS.read(sid)["fit"]
    print(json.dumps({"stick": sid, "added": added, "witnesses": f["witnesses"], "record": len(f["record"]),
                      "open": f["open"]}, indent=1))
    return 0


# ── run one data entry ───────────────────────────────────────────────────────────────────────────
def run(entry: Dict[str, Any]) -> int:
    """Seal every seal (abort on the first that does not hold), then create each stick and mint its marks —
    the shape every data stick had as a function: seals -> TS.create -> _mint_marks."""
    from . import tickstick as TS
    if "handler" in entry:
        raise StickError(f"{entry.get('name')}: a handler entry runs through tools/tick.py, not the loader")
    hashes: Dict[str, Optional[str]] = {}
    for s in entry.get("seals", []):
        hashes[s["key"]] = seal(s)
    if not all(hashes.values()):
        print("a seal failed; aborting"); return 1
    if hashes:
        print("sealed", len(hashes), "seal(s):", " ".join(f"{k}={h[:12]}" for k, h in hashes.items()))
    rc = 0
    for st in entry["sticks"]:
        r = TS.create(st["question"], statement=st.get("statement", ""), field=st.get("field", ""),
                      references=st.get("references"))
        if not r.get("ok"):
            print("REFUSED stick:", r.get("error")); return 1
        sid = r["id"]
        print(("opened " if not r.get("existed") else "exists ") + sid)
        marks = []
        for m in st.get("marks", []):
            kw: Dict[str, Any] = {}
            if "seal" in m:
                kw["seal"] = hashes[m["seal"]]
            for k in ("source", "up_to", "unit"):
                if k in m:
                    kw[k] = m[k]
            marks.append((m["kind"], m["claim"], kw or None))
        if marks:
            rc |= mint_marks(sid, marks, by=st["by"])
    return rc
