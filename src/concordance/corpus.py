def default_corpus(path: Optional[Path] = None) -> Corpus:
    global _DEFAULT
    if _DEFAULT is None:  # double-checked lock: build once, even under concurrent first-hits
        with _DEFAULT_LOCK:
            if _DEFAULT is None:
                from time import perf_counter as _pc
                from . import frozen_cache as _fc
                from .systems import rss_kb as _rss
                df: Dict[str, int] = {}
                fz: Dict[str, tuple] = {}
                LOAD_PHASES.clear()
                _t0 = _pc()
                _r0 = _rss()
                # THE FROZEN CACHE (2026-10-08). The frozen shelves' document-frequency table and compact index
                # are pure functions of the files that hold frozen cards; a boot whose inputs are unchanged loads
                # them instead of tokenizing every frozen card again, and (v3) reads from each cached file only
                # the lines that stayed resident, by recorded byte offset. Keyed on exactly the BIG contributors
                # (>= frozen_cache.min_contribution() frozen cards) + the freeze set; small, volatile contributors
                # (receipt_cards, verified_cards - a few domain-shelf cards, growing with every seal) are processed
                # live every boot and merged, so the key holds still across seals and nothing is ever missing.
                # RSS is read at each boundary so the memory of each structure is measured, not estimated.
                p_main = path or _cards_path()
                data_dir = p_main.parent
                frozen = frozen_shelves()
                state = "off"
                skip: Optional[set] = None
                offsets_in: Optional[Dict[str, List[int]]] = None
                offsets_out: Optional[Dict[str, List[int]]] = None
                cache_load_ms = cache_read_ms = cache_decode_ms = cache_save_ms = 0.0
                n_cached_fz = 0

                def _resolve(name: str) -> Path:
                    return p_main if name == p_main.name else data_dir / name

                if _fc.enabled() and frozen:
                    state = "miss"
                    _tc = _pc()
                    cpath = _fc.cache_path(data_dir)
                    names = _fc.peek_contributors(cpath) or []
                    files = [_resolve(n) for n in names]
                    if names and all(f.exists() for f in files):
                        got = _fc.load(cpath, _fc.make_key(files, frozen))
                        if got:
                            df, fz = got["df"], got["fz"]          # the loaded tables ARE the tables - no copy
                            skip = set(got["contributors"])
                            offsets_in = got["offsets"]
                            cache_read_ms, cache_decode_ms = got["read_ms"], got["decode_ms"]
                            n_cached_fz = len(fz)
                            state = "hit"
                    if state == "miss":
                        offsets_out = {}
                    cache_load_ms = (_pc() - _tc) * 1000.0
                nofile: Dict[str, Any] = {"df": {}, "ids": []}
                _r1 = _rss()
                contrib: Dict[str, List[int]] = {}
                cards = load_cards(path, _df_out=df, _frozen_out=fz, _skip_frozen_in=skip,
                                   _contrib_out=contrib, _offsets_in=offsets_in, _offsets_out=offsets_out,
                                   _nofile_out=(nofile if offsets_out is not None else None))
                _t1 = _pc()
                _r2 = _rss()
                if state == "hit":
                    LOAD_PHASES["frozen_cards_cached"] = n_cached_fz   # served from the cache, never seen by load_cards
                cached_names: List[str] = sorted(skip) if skip else []
                cached_skip: List[str] = sorted(n for n, o in (offsets_in or {}).items() if not o)
                if state == "miss":
                    _ts = _pc()
                    mn = _fc.min_contribution()
                    big = sorted(n for n, (k, _r) in contrib.items() if k >= mn)
                    small = [_resolve(n) for n, (k, _r) in contrib.items() if 0 < k < mn]
                    big_files = [_resolve(n) for n in big]
                    if big and all(f.exists() for f in big_files):
                        if small or nofile["ids"] or nofile["df"]:
                            df_c, fz_c = _without_files(df, fz, small, frozen)      # copies, small files subtracted
                            for t, n in nofile["df"].items():                        # ... and the non-file frozen cards
                                m = df_c.get(t, 0) - n
                                if m > 0:
                                    df_c[t] = m
                                else:
                                    df_c.pop(t, None)
                            for cid in nofile["ids"]:
                                fz_c.pop(cid, None)
                        else:
                            df_c, fz_c = df, fz
                        offs = {n: list((offsets_out or {}).get(n, [])) for n in big}   # [] = nothing resident
                        if _fc.save(_fc.cache_path(data_dir), _fc.make_key(big_files, frozen), df_c, fz_c, big, offs):
                            cached_names = big
                            cached_skip = sorted(n for n, o in offs.items() if not o)
                    cache_save_ms = (_pc() - _ts) * 1000.0
                _DEFAULT = Corpus(cards, df_extra=df, frozen_idx=fz)
                _t2 = _pc()
                _r3 = _rss()

                def _delta(a, b):
                    return (b - a) if (a is not None and b is not None) else None

                LOAD_PHASES.update({"load_cards_ms": round((_t1 - _t0) * 1000.0, 1),
                                    "index_build_ms": round((_t2 - _t1) * 1000.0, 1),
                                    "total_ms": round((_t2 - _t0) * 1000.0, 1),
                                    "resident_cards": len(cards), "frozen_index": len(fz),
                                    "df_tokens": len(df),
                                    "frozen_cache": state, "cache_load_ms": round(cache_load_ms, 1),
                                    "cache_read_ms": round(cache_read_ms, 1), "cache_decode_ms": round(cache_decode_ms, 1),
                                    "cache_save_ms": round(cache_save_ms, 1),
                                    "cached_contributors": cached_names, "cached_skip_files": cached_skip,
                                    "rss_kb_cache_delta": _delta(_r0, _r1), "rss_kb_load_delta": _delta(_r1, _r2),
                                    "rss_kb_index_delta": _delta(_r2, _r3), "rss_kb_total_delta": _delta(_r0, _r3)})
    return _DEFAULT


def _without_files(df: Dict[str, int], fz: Dict[str, tuple], files: List[Path], frozen) -> tuple:
    """Copies of the frozen DF table and index with the frozen cards of `files` removed — the small, volatile
    contributors that must stay LIVE (so the cache key holds still across seals). Re-reads only those files,
    which are small by definition, mirroring load_cards' own gate (shelve, then the shelf test)."""
    df2, fz2 = dict(df), dict(fz)
    for fp in files:
        try:
            with open(fp, encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        c = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    if not (isinstance(c, dict) and c.get("id")):
                        continue
                    shelve(c)
                    if c.get("shelf") not in frozen:
                        continue
                    for t in set(_tokens(_card_text(c))):
                        n = df2.get(t, 0) - 1
                        if n > 0:
                            df2[t] = n
                        else:
                            df2.pop(t, None)
                    fz2.pop(c["id"], None)
        except OSError:
            continue
    return df2, fz2


def subject_of(query: str) -> Optional[str]:
    """The single word this asking is ABOUT — the globally rarest content token — or None.

    The same computation the merge partition in search() already performs, exposed so a CALLER
    can hold results to it. Needed because a scoped search cannot see its own blindness: within a
    deck whose shelves never contain "wesleyan", the local IDF has no such token, the partition
    falls back to the next-best word ("church"), and six confession cards about the church in
    general come back looking relevant. Only the GLOBAL corpus knows what the question was about;
    this hands that knowledge to the routing layer that chose the scope.
    """
    from .corpus_db import _STOP
    toks = {t for t in _tokens(query) if t not in _STOP}
    if not toks:
        return None
    c = default_corpus()
    return c._subject_of(toks, c._idf(toks))


def search(query: str, limit: int = 25, include_witness: bool = True,
           shelves: Optional[set] = None) -> List[dict]:
    """Ranked search over the default corpus (cards.jsonl) — the floor's retrieval primitive.
    The keeping is shared across both surfaces by default (the .com includes the religious
    cards too); pass include_witness=False for an optional secular-only view. `shelves` scopes
    the search to a deck (the Hare fast-path).

    When shelves are FROZEN (riding the shards), their resident stubs only match on title —
    so the shard FTS (which indexes the full text) fills the remaining slots, and any stub
    that made the cut is rehydrated. The reader never sees a lighter answer because the
    shelf rode the shard."""
    corpus = default_corpus()
    out = corpus.search(query, limit, include_witness, shelves)
    frozen = frozen_shelves() if corpus._froze else frozenset()   # only a corpus built with freeze awareness merges shard freight
    if frozen and (shelves is None or (set(shelves) & frozen)) and len(out) < limit:
        from . import corpus_db
        corpus_db.thaw_for(*frozen)
        have = {c.get("id") for c in out}

        # THE SUBJECT PARTITION MUST HOLD ON BOTH SIDES OF THE MERGE, and I learned that the hard
        # way twice in one day. The resident ranker got the partition and the live wire STILL
        # answered "Wesleyan Church" with a Kensington church directory and "The war of Antichrist"
        # at positions 4-8 — because those shelves are frozen, so their hits arrive from the shard's
        # bm25 and never met the rule. Exactly the shape of the stopword bug this afternoon: two
        # matchers, one fixed, the reader unchanged.
        #
        # The shard cannot apply this itself (FTS5 ranks inside SQLite), so the gate goes HERE, at
        # the one point every frozen hit must pass through. Cheap: one token test per candidate.
        from .corpus_db import _STOP          # the one list every matcher uses
        q_tokens = {t for t in _tokens(query) if t not in _STOP}
        subject = corpus._subject_of(q_tokens, corpus._idf(q_tokens)) if q_tokens else None

        for hit in corpus_db.search(query, limit=limit * 3, include_witness=include_witness):
            if (hit.get("shelf") not in frozen or hit.get("id") in have
                    or (shelves is not None and hit.get("shelf") not in shelves)
                    or not is_public(hit)):
                continue        # resident shelves are already fully scored — merge only frozen freight
            if subject and not (Corpus.subject_family(subject) & set(_tokens(_card_text(hit)))):
                continue        # lacks what the question is about — the same partition, same rule
            out.append(hit)
            have.add(hit.get("id"))
            if len(out) >= limit:
                break

    # THE SEMANTIC SUPPLEMENT — the answer-path, live (docs/THE_WATCH.md step 5). Only when there is ROOM
    # below the lexical hits (a thin result is the paraphrase case), reach matches that share MEANING but
    # not words: expand the query with sealed meaning-neighbours and run the SAME ranker on the expanded
    # query. Appended BELOW, never reordering the trusted lexical hits; the ranker's own subject partition
    # (now seeing the expansion terms) keeps it honest. Labeled via="meaning". It can only ADD, never hurt.
    if len(out) < limit:
        try:
            from . import semantic
            if semantic.available():
                extra = semantic.expand(query.split())
                if extra:
                    have = {c.get("id") for c in out}
                    exp_q = query + " " + " ".join(extra)
                    for hit in corpus.search(exp_q, limit, include_witness, shelves):
                        if hit.get("id") in have or not is_public(hit):
                            continue
                        hit = dict(hit)
                        hit["via"] = "meaning"
                        out.append(hit)
                        have.add(hit.get("id"))
                        if len(out) >= limit:
                            break
        except Exception:
            pass                      # the supplement must never break the trusted search
    return [rehydrate(c) for c in out]


# ── Question retrieval: strip the frame, keep the subject (2026-09-25) ──────────────────────────────
# Matt: "when you remove the context of a name and place you have a much more limited set of responses."
# A free-text question carries a FRAME (a name, a request, a politeness) around its SUBJECT; the full-text
# engine matches the frame's words too. Proven live: "Can you tell me what the Bible says about being
# anxious and worried?" ranked "The Great Schism (1054)" #1 (it matched 'says'/'Bible') and the real
# "Do Not Worry" teaching never appeared — while the subject "anxious and worried" ranks the teaching #1.
# The airlock, applied to the query: strip the leading frame to the necessity-only subject before search.
_Q_FRAME = re.compile(
    r"^\s*(?:"
    r"please\s+|"
    r"(?:can|could|would|will|do)\s+(?:you|u|ya)\s+(?:please\s+)?(?:tell|explain|teach|show|help|give|find)\s+(?:me|us)?\s*|"
    r"(?:tell|explain|teach|show)\s+(?:me|us)\s+(?:about\s+)?|"
    r"i\s+(?:want|need|would\s+like|'?d\s+like)\s+to\s+(?:know|understand|learn)\s+(?:about\s+)?|"
    # "what does the Bible say about" AND the relative-clause "what the Bible says about" / "the Bible says about"
    r"(?:what|which)?\s*(?:does|do|did|is|are|was|were)?\s*(?:the\s+)?(?:bible|scripture|scriptures|word|god|jesus|lord|christ|gospel)\s+(?:say|says|said|teach|teaches|tell|tells|state|states)\s+(?:me\s+|us\s+)?(?:about\s+)?|"
    r"what\s+(?:does|do|did)\s+[a-z]+(?:\s+[a-z]+){0,3}\s+say\s+about\s+|"
    r"(?:what|how|why|where|when|who|whether)\s+(?:is|are|was|were|do|does|did|can|should|would|to)\s+(?:the\s+|a\s+|an\s+)?|"
    r"(?:what|how|why|where|when|who)\s+(?:the\s+|a\s+|an\s+)?"
    r")", re.I)


def query_subject(text: str) -> str:
    """Strip a leading question/request FRAME so search matches the subject, not the scaffold.
    Deterministic and conservative: only a recognized leading frame is removed, and the raw text is kept
    whenever the strip would leave nothing real — never over-strip a bare or odd query (a miss stays a
    miss). No model; the airlock's principle applied to a query."""
    s = re.sub(r"\s+", " ", (text or "").strip())
    if not s:
        return s
    for _ in range(3):                                  # stacked frames: "can you tell me" + "what X says about"
        nxt = _Q_FRAME.sub("", s, count=1).strip(" ?.!,")
        if nxt == s:
            break
        if len(nxt) < 2 or not any(ch.isalpha() for ch in nxt):
            break                                       # would over-strip — keep the last real subject
        s = nxt
    return s


# Spellings of the same Chinese classics and names (Wade-Giles · pinyin · the older missionary
# forms). Multi-word or proper names only — a bare "tao"/"dao" swap would reach Taos and the Dao
# of unrelated titles. Lower-case; matched as substrings of the lower-cased query.
_ROMANIZATION = (
    ("tao te ching", "tao teh king", "tao-teh-king", "daodejing", "dao de jing", "tao-te-ching"),
    ("lao tzu", "laozi", "lao-tze", "lao tze", "lao-tzu", "lao tsu"),
    ("chuang tzu", "zhuangzi", "chuang-tzu", "chuang tsu"),
    ("i ching", "yijing", "yi king", "book of changes"),
    ("sun tzu", "sunzi", "sun-tzu"),
    ("confucius", "kongzi", "kung fu-tzu", "k'ung fu-tzu"),
    ("mencius", "mengzi"),
    ("the analects", "lun yu", "lunyu"),
)


def _alias_queries(query: str) -> List[str]:
    """The query re-spelled through each romanization group it touches (one swap per variant),
    deduped, the original excluded. Pure; empty for a query naming none of the works."""
    q = str(query or "")
    low = q.lower()
    outq: List[str] = []
    for group in _ROMANIZATION:
        for form in group:
            if form in low:
                i = low.index(form)
                for alt in group:
                    if alt == form:
                        continue
                    cand = q[:i] + alt + q[i + len(form):]
                    if cand.lower() != low and cand not in outq:
                        outq.append(cand)
                break
    return outq


def search_question(query: str, limit: int = 25, include_witness: bool = True,
                    shelves: Optional[set] = None) -> List[dict]:
    """Search a free-text QUESTION: the necessity-only subject first (frame stripped), then the raw text,
    merged subject-first and deduped. Recall-safe by construction — the raw results are always included,
    so this can only LIFT the on-subject cards ahead of frame-matched noise, never drop a hit. For a bare
    query with no frame it is exactly search()."""
    raw = str(query or "")
    subj = query_subject(raw)
    seen: set = set()
    out: List[dict] = []

    def _take(src: str) -> None:
        for c in search(src, limit=limit, include_witness=include_witness, shelves=shelves):
            cid = c.get("id")
            if cid and cid in seen:
                continue
            if cid:
                seen.add(cid)
            out.append(c)
            if len(out) >= limit:
                break

    # The literal question first — subject (frame stripped) then raw — always kept ahead.
    for src in ([raw] if subj == raw else [subj, raw]):
        if len(out) >= limit:
            break
        _take(src)

    # ROMANIZATION (2026-10-02): the keeping holds Legge's "Tao Teh King" (Gutenberg 216) and Carus's
    # "Tao-teh-king"; a reader asks for the "Tao Te Ching" or the "Daodejing" — Wade-Giles, pinyin and
    # the older spellings never met, so the classic was in the house and unreachable (measured: ask
    # "what does the tao te ching say about the way" -> nothing). Each alias group is one work or one
    # name; the literal query keeps the front slots and the aliases only fill what remains.
    for alt in _alias_queries(subj if subj != raw else raw):
        if len(out) >= limit:
            break
        _take(alt)

    # RECALL, SHARPENED BY THE THESAURUS. Only when the literal query UNDER-FILLS: broaden the
    # subject word by a few WordNet synonyms so "automobile" reaches material that only says "car".
    # Recall-safe by construction — literal hits already hold the front slots; synonyms merely fill
    # what remains, deduped. Zero cost when results are plentiful, and a no-op when no thesaurus is
    # present (offline-optional, like the shards). Synonyms WIDEN what can be found; they never
    # redefine the question — so the subject is chosen among the ASKED words, never a synonym.
    if len(out) < limit:
        from . import thesaurus
        if thesaurus.available():
            from .corpus_db import _STOP
            corpus = default_corpus()
            asked = {t for t in _tokens(subj) if t not in _STOP} \
                or {t for t in _tokens(raw) if t not in _STOP}
            subject = corpus._subject_of(asked, corpus._idf(asked)) if asked else None
            if subject:
                for syn in thesaurus.expand_subject(subject, limit=4):
                    if len(out) >= limit:
                        break
                    _take(syn)
    return out


# ── Library primitives (ported from 1.0's card tools, over the same corpus) ──────────────

def _brief(c: dict) -> Dict[str, Any]:
    b = {"id": c.get("id"), "title": c.get("title"), "shelf": c.get("shelf"),
         "surface": c.get("surface"), "snippet": (c.get("body", "") or "")[:200]}
    if c.get("call"):
        b["call"] = c.get("call")          # the Dewey call number, so a browser sees where it sits
    if c.get("facets"):
        b["facets"] = c.get("facets")
    return b


def get_card(card_id: str) -> Optional[dict]:
    """Fetch one PUBLIC card (the full record) by id, or None. Non-public cards
    (private / public_review / archived / quarantine / retracted) are never returned —
    this is the boundary render_card_html and /card rely on."""
    c = default_corpus().full((card_id or "").strip())   # resident, or rehydrated from the shard
    return c if (c is not None and is_public(c)) else None


def browse(shelf: Optional[str] = None, limit: int = 20, offset: int = 0,
           call: Optional[str] = None, facet: Optional[str] = None) -> Dict[str, Any]:
    """Paginated browse over the keeping. Filter by shelf, by CALL-NUMBER prefix (walk the Dewey
    tree, e.g. call='classics.augustine'), or by controlled FACET ('verse', or 'person:david').
    Returns briefs PLUS the call-tree children under the current prefix, so a reader can walk a
    shelf down one level at a time."""
    cp = default_corpus()
    pref = (call or "").strip().lower().rstrip(".")
    children = [{"call": c, "count": n} for c, n in cp.call_children(pref)[:60]]  # precomputed
    if pref:
        cids = cp.cids_for_call(pref)                 # walk — bounded by distinct call numbers
    else:
        cids = list(cp._public_sorted)                # whole keeping (resident + frozen index), pre-sorted
    if shelf:
        cids = [cid for cid in cids if cp._shelf_of(cid) == shelf.lower()]   # shelf from call for frozen
    if facet:
        # facets are resident-only (a frozen card's facets live on the shard, not the compact index),
        # so facet-browse covers the resident shelves; the call-walk reaches the frozen ones.
        fkey, _, fval = facet.strip().lower().partition(":")
        def _has(cid: str) -> bool:
            fs = cp.cards.get(cid, {}).get("facets") or {}
            if not isinstance(fs, dict) or fkey not in fs:
                return False
            return (not fval) or any(fval == str(v).lower() for v in (fs.get(fkey) or []))
        cids = [cid for cid in cids if _has(cid)]
    if (shelf or facet) and not pref:
        cids = sorted(cids, key=lambda cid: (cp._call_of(cid) or cp._shelf_of(cid), cp._title_of(cid)))
    total = len(cids)
    offset = max(0, offset)
    limit = max(1, min(limit, 100))
    page = cids[offset:offset + limit]
    briefs = []
    for cid in page:                                  # full(): resident, or rehydrated from the shard
        fc = cp.full(cid)
        if fc is not None:
            briefs.append(_brief(fc))
    return {"total": total, "offset": offset, "limit": limit, "shelf": shelf,
            "call": call, "facet": facet, "children": children, "cards": briefs}


def stats() -> Dict[str, Any]:
    """Counts over the WHOLE keeping — total, by shelf, by surface — resident cards AND the frozen
    index (lazy stubs), so the numbers reflect the full keeping, not just what's held in RAM."""
    from collections import Counter
    cp = default_corpus()
    ids = cp._public_sorted                          # every public id (resident + frozen index)
    by_shelf: Counter = Counter(cp._shelf_of(cid) or "?" for cid in ids)
    by_surface: Counter = Counter(cp._surface_of(cid) for cid in ids)
    out = {"total": len(ids),
           # EVERY shelf, never the largest 40 — the browse dropdown is built from this; a cap hides
           # shelves the one control meant to reach them.
           "by_shelf": dict(by_shelf.most_common()),
           "by_surface": dict(by_surface)}
    fz = frozen_shelves()
    if fz:
        # named, never silent: these shelves ride the SQLite shards (bodies + graph rehydrated on
        # read); resident holds only a compact (call, title, surface) index for them.
        out["frozen_shelves"] = sorted(fz)
    return out


def daily(seed: Optional[str] = None) -> Optional[dict]:
    """A deterministic 'card of the day' — same card all day, different each day. Stable: the
    seed (default today's UTC date) hashes to an index over the WHOLE keeping (resident + frozen)."""
    import hashlib
    import time as _time
    cp = default_corpus()
    ids = cp._public_sorted
    if not ids:
        return None
    if seed is None:
        seed = _time.strftime("%Y-%m-%d", _time.gmtime())
    idx = int(hashlib.sha256(seed.encode("utf-8")).hexdigest(), 16) % len(ids)
    return cp.full(ids[idx])                          # resident, or rehydrated from the shard


def connections(card_id: str, limit: int = 10) -> Optional[Dict[str, Any]]:
    """Cards related to one card — its explicit links plus same-shelf siblings. None if absent.
    Same-shelf siblings come from the call-tree (the shelf is the call's head), so they include
    frozen cards, rehydrated from the shard for their brief."""
    cp = default_corpus()
    c = get_card(card_id)
    if c is None:
        return None
    shelf = (c.get("shelf") or "")
    lim = max(1, min(limit, 50))
    sib_ids = [cid for cid in cp.cids_for_call(shelf.lower()) if cid != card_id][:lim]
    sibs = []
    for cid in sib_ids:
        fc = cp.full(cid)
        if fc is not None and is_public(fc):
            sibs.append(_brief(fc))
    links = c.get("links") or c.get("connections") or c.get("refs") or []
    return {"id": card_id, "shelf": shelf, "links": links, "same_shelf": sibs}


def locate(q: str, limit: int = 5) -> Dict[str, Any]:
    """Find the card for a query: exact id, then title match, else fall back to ranked search."""
    # found: "q or ''" only substitutes the fallback for a FALSY q — a truthy non-string (an
    # int from an uncoerced MCP tool call arg) survives past that guard and crashes on
    # ".strip()". Matches corpus.search()'s fix, same module.
    q = (str(q) if q else "").strip()
    if not q:
        return {"query": q, "by": "none", "matches": []}
    cp = default_corpus()
    idc = cp.full(q)                                  # exact id — resident or frozen (rehydrated)
    if idc is not None and is_public(idc):
        return {"query": q, "by": "id", "matches": [_brief(idc)]}
    ql = q.lower()
    hits: List[str] = []
    for cid, c in cp.cards.items():                   # resident titles
        if is_public(c) and ql in (c.get("title") or "").lower():
            hits.append(cid)
            if len(hits) >= limit:
                break
    if len(hits) < limit:                             # then frozen titles (from the compact index)
        for cid, fz in cp._frozen.items():
            if ql in (fz[1] or "").lower():
                hits.append(cid)
                if len(hits) >= limit:
                    break
    if hits:
        matches = [_brief(fc) for cid in hits[:limit] for fc in [cp.full(cid)] if fc]
        return {"query": q, "by": "title", "matches": matches}
    return {"query": q, "by": "search", "matches": [_brief(c) for c in search(q, limit=limit)]}


def health() -> Dict[str, Any]:
    """Corpus health — is the keeping loaded and sound (whole keeping: resident + frozen index)."""
    cp = default_corpus()
    ids = cp._public_sorted
    n = len(ids)
    resident_body = sum(1 for c in cp.cards.values() if is_public(c) and (c.get("body") or "").strip())
    return {"ok": n > 0, "total": n,
            "with_body": resident_body + len(cp._frozen),   # frozen bodies ride the shard
            "shelves": len({cp._shelf_of(cid) for cid in ids}),
            "surfaces": sorted({cp._surface_of(cid) for cid in ids})}


def gauges() -> Dict[str, Any]:
    """THE GAUGE PANEL — every invented ranking constant, located on the measured curve.

    Matt, 2026-08-02: *"Rate functions relate to the total amount collected... All of this is
    Math. We should be building formulas and verifiers that meet each need."* — and the same day
    the first measurement through this lens found `min_idf = 1.5` admitting 100.0% of 300,463
    tokens: a distinctiveness floor tuned when the corpus was small, gone silently vacuous as it
    grew. A constant is a promise about a distribution; when the distribution moves, the promise
    rots unless something re-measures it. This does, from the live index, every time it is asked.

    Verdicts are three-state and blunt: VACUOUS (the constant excludes almost nothing — dead
    weight wearing a guard's uniform), BINDING (doing real work), or the number speaks for
    itself. It FLAGS; it never auto-tunes — re-deriving a ranking constant is a change to what
    every reader sees and goes through the gate with a before/after probe battery, not through a
    monitor. Every figure carries its means, per the coverage rule.
    """
    import math as _math
    c = default_corpus()
    dfs = sorted((len(v) + c._df_extra.get(k, 0) for k, v in c._by_token.items()),
                 reverse=True)
    n_tokens = len(dfs)
    n_cards = c._n

    # the Zipf fit — the constant-ratio growth law the whole index rides on
    lo, hi = 10, min(10001, n_tokens)
    pts = [( _math.log(r), _math.log(dfs[r - 1])) for r in range(lo, hi) if dfs[r - 1] > 0]
    slope = r2 = None
    if len(pts) > 100:
        mx = sum(p[0] for p in pts) / len(pts)
        my = sum(p[1] for p in pts) / len(pts)
        denom = sum((x - mx) ** 2 for x, _ in pts)
        if denom > 0:
            slope = sum((x - mx) * (y - my) for x, y in pts) / denom
            ss_res = sum((y - (my + slope * (x - mx))) ** 2 for x, y in pts)
            ss_tot = sum((y - my) ** 2 for _, y in pts) or 1.0
            r2 = 1 - ss_res / ss_tot

    # min_idf on the curve: what fraction of the vocabulary does the floor actually admit?
    cut_df = n_cards / _math.exp(self_min := c.min_idf)
    admitted = sum(1 for d in dfs if d < cut_df)
    admit_frac = admitted / n_tokens if n_tokens else 0.0

    # the candidate cap: how many tokens could flood it (the starvation class of bug)
    flood = sum(1 for d in dfs if d > 600)

    return {
        "zipf": {"slope": round(slope, 3) if slope is not None else None,
                 "r2": round(r2, 4) if r2 is not None else None,
                 "means": f"log-log fit over ranks {lo}-{hi - 1} of {n_tokens:,} tokens"},
        "min_idf": {"value": self_min, "admits_fraction": round(admit_frac, 4),
                    "verdict": ("VACUOUS" if admit_frac > 0.99
                                else "BINDING" if admit_frac < 0.90 else "MARGINAL"),
                    "means": f"tokens with df < {int(cut_df):,} of {n_cards:,} cards"},
        "candidate_cap": {"value": 600, "tokens_that_flood": flood,
                          "means": "tokens with df > cap; rarest-first seeding makes the cap "
                                   "safe, this counts how often it is exercised"},
        "subject_tier": {"value": SUBJECT_TIER,
                         "max_idf": round(max((_math.log(n_cards / (d + 1)) for d in dfs[-1:]),
                                              default=0.0), 2),
                         "means": "the tier must exceed any reachable tf-idf sum; max single-"
                                  "token idf shown for scale"},
        "population": {"tokens": n_tokens, "cards": n_cards},
    }
