def _tokens(text: str) -> List[str]:
    return re.findall(r"[a-zA-Z][a-zA-Z']{1,}", (text or "").lower())


def _card_text(card: dict) -> str:
    src = card.get("source") or {}
    return " ".join([
        card.get("title", ""),
        (card.get("body", "") or "")[:1000],
        " ".join(card.get("bands") or []),
        src.get("ref", ""),
        src.get("label", ""),
    ]).lower()


PUBLIC_STAGES = frozenset({"public", "featured"})

# Disallowed-to-REDISTRIBUTE license markers. Two classes are a legal issue to serve publicly:
# share-alike (CC-BY-SA — its viral copyleft could pull the WHOLE corpus under SA) and
# non-commercial (CC-BY-NC* — forbids the free-to-all use that is the point). PD / CC0 / CC-BY
# (attribution-only) are fine, credited by each card's own source label. Mirror of the mint-side
# guard in tools/card_sources.py (_DISALLOWED_LICENSE) — the two boundaries stay in step.
_DISALLOWED_LICENSE = ("cc-by-sa", "cc by-sa", "share-alike", "sharealike",
                       "cc-by-nc", "cc by-nc", "non-commercial", "noncommercial")
# Legacy sources that ARE disallowed-license but whose cards were minted before the guard and carry
# only the SOURCE NAME in their label, never the license string. OEIS (CC-BY-NC-SA) is the live
# case — 6,000 cards served under a bare "OEIS — …" label, slipping the marker scan (found 2026-08-08
# in the pre-launch shelf audit). Matched by source name (label + url) so the name alone withholds.
_DISALLOWED_SOURCE = ("oeis", "phoible", "drugcentral")

# Back-compat alias: the flag on a frozen-shelf stub and older callers is still named `share_alike`.
_SHARE_ALIKE = _DISALLOWED_LICENSE


def _is_share_alike(card: dict) -> bool:
    """True iff a card declares a license we may not publicly REDISTRIBUTE — share-alike (CC-BY-SA)
    or non-commercial (CC-BY-NC*) — OR names a known such source. Read from the free-text source
    label, `source.url`, and any `extra.license` (a structured `license` field would be more robust;
    tracked as a follow-up). HYG + PHOIBLE match by their CC-BY-SA label; OEIS matches by source name.

    A FROZEN-SHELF STUB drops `source`/`extra` to save memory, so it carries a precomputed
    `share_alike` bool (set at stub-build time while the label was still present) — honoured here
    first, so is_public() judges a stub exactly as it judges the full card. Without this, search
    (which runs over stubs) leaked CC-BY-SA cards that card_get correctly withheld (found live)."""
    flag = card.get("share_alike")
    if flag is not None:
        return bool(flag)
    src = card.get("source")
    label = (src.get("label") if isinstance(src, dict) else "") or ""
    url = (src.get("url") if isinstance(src, dict) else "") or ""
    extra = card.get("extra")
    lic = (extra.get("license") if isinstance(extra, dict) else "") or ""
    if any(m in (str(label) + " " + str(lic)).lower() for m in _DISALLOWED_LICENSE):
        return True
    # a known disallowed source recognised by name, for legacy cards whose label lacks the license
    return any(s in (str(label) + " " + str(url)).lower() for s in _DISALLOWED_SOURCE)

# Larger than any reachable TF-IDF score, so cards holding the query's rarest word form a
# strictly higher tier than those that do not. A partition, not a weight: no amount of
# repeating a common word can cross it.
SUBJECT_TIER = 1000.0

# A theory card outranks an incidental mention of the same words. Deliberately a WEIGHT and not a
# tier: the subject partition still decides who is in the running, and this only orders those who
# already are. Set at 4.0 — above the survival field library's 3.0 (a how-to should still win a
# how-to question) and well under the exact-title 9.0, so naming a card by its title still wins.
THEORY_WEIGHT = 4.0

# THE RANKER WAS BLIND TO SUBSTANCE VS HEADWORD (docs/SOP/subsystems/keeping.md's own "Refine" —
# the highest-leverage open item, 2026-09-02). ~67% of the keeping are stubs (a pronunciation
# guide, a bare title+link — ops.STUB_BODY_CHARS defines the line), and the subject partition
# above is lexical presence only: it can tell "about this" from "not about this," never a thin
# gloss from a real excerpt that answers the question. A weight, not a tier, like THEORY_WEIGHT —
# it only ever reorders cards the partition already admitted. Set modestly (well under
# THEORY_WEIGHT) because it distinguishes within EVERY tier a query reaches, not one narrow shelf.
SUBSTANCE_WEIGHT = 2.0


def is_public(card: dict) -> bool:
    """True iff a card may appear on ANY public read path — an ALLOWLIST, not a denylist.
    ONE source of truth (graph.py imports this too, so the two can never diverge): every
    stage except public/featured — private, public_review, archived, quarantine, retracted —
    is withheld. A denylist here (archived/quarantine only) is exactly what leaked the
    operator's private cards onto the public surface. On top of the stage allowlist, two
    withholding guards (more restrictive, never less): share-alike-licensed cards (CC-BY-SA —
    a legal issue to redistribute) and generated cards (the conduit contract) never go public."""
    if not isinstance(card, dict) or card.get("retracted"):
        return False
    if (card.get("lifecycle_stage") or "public") not in PUBLIC_STAGES:
        return False
    # LICENSE (red team 2026-08-06, Matt's call "drop what could get us in trouble"): never publicly
    # REDISTRIBUTE share-alike content — its copyleft could pull the whole corpus under SA. Withheld
    # here, not deleted (the bodies stay archived on the drive). A PD stub card ABOUT each such source
    # still serves, so the shelf is not a silent hole. See _is_share_alike.
    if _is_share_alike(card):
        return False
    # The conduit contract at the serving boundary: a generated card is never served publicly.
    if card.get("generated") is True:
        return False
    return True


# ── The freeze (D4) — the heavy shelves ride the shards, the graph stays home ────────────
# Matt, 2026-07-27/28: the two processes held ~2.8 GB RSS each with every shelf resident.
# Profiled per-structure (2026-07-28): dictionary/gutenberg/geography/taxonomy carry 258.7 MB
# serialized, and ~70% of it is body/bands/extra/source — none of which the GRAPH needs.
# With CONCORDANCE_FREEZE_SHELVES set (and shards present), those shelves load as STUBS:
# identity + connections stay resident so the nesting stays whole (zero orphans, titles
# findable); bodies, bands, and provenance rehydrate from the SQLite shards on read.
# Opt-in and reversible: unset the env and everything loads resident exactly as before.

# What a stub keeps: identity, the public/withheld boundary, and the graph. `retracted`,
# `lifecycle_stage`, `generated`, and the computed `share_alike` bool stay so is_public() judges a
# stub exactly as it judges the full card — the license lives in `source` (dropped on a stub), so
# it is precomputed at stub-build time (search runs on stubs; without this it leaked CC-BY-SA).
_STUB_KEEPS = frozenset({"id", "title", "shelf", "surface", "kind", "box", "visibility",
                         "lifecycle_stage", "retracted", "generated", "share_alike", "connections",
                         "call", "facets"})  # the Dewey call number + controlled facets, kept for browse


def call_number(card: dict) -> str:
    """The Dewey-style call number `shelf.class.item`, DERIVED from shelf + box — both of which are
    resident in RAM even for a frozen stub, so every card (the 637k on the shards included) connects
    to the same tree with no shard read. Must match tools/classify_keeping.call_number exactly."""
    shelf = (card.get("shelf") or "misc").strip().lower()
    box = (card.get("box") or "").strip().lower()
    if not box:
        return shelf
    if "_" in box:
        cls, item = box.split("_", 1)
    else:
        cls, item = box, ""
    return ".".join(p for p in (shelf, cls, item) if p)


# ── The additional sublayers (deepening the flat frozen shelves) ─────────────────────────────
# `call_number` alone leaves the big acquired shelves flat: their box is the generic "source",
# so dictionary/pronunciation/gutenberg/geography/taxonomy/… all collapse to one `<shelf>.source`
# bucket of 70–150k cards. But each shelf carries its REAL order in its resident title + bands —
# a wordlist walks A→Z, books shelve by author, places by country, verse cards by book, numbered
# series by range. `deep_call` reads only what is already there (no imposed scheme) and returns a
# finer call; a shelf with no known sublayer, or a card missing the field, degrades to
# `call_number()`/alphabetical, never worse. It uses `bands` when present (the classifier writes
# over full cards, where bands live) and degrades to title-only when they are gone (a frozen stub
# in RAM), so the same card lands on the same shelf both ways. Must match tools/classify_keeping.
_RANKS = frozenset({"domain", "kingdom", "phylum", "class", "order", "family", "genus", "species",
                    "subphylum", "subclass", "suborder", "subfamily", "tribe", "superfamily",
                    "infraclass", "superorder", "infraorder", "subgenus", "subspecies", "clade"})
_BOOK_REF_RE = re.compile(r"^\s*(.+?)\s+(\d+):(\d+)")   # "Genesis 1:1 (Hebrew)" -> book, ch, vs
_YEAR_TAIL_RE = re.compile(r"\((-?\d{1,4})\)\s*$")      # "... (1815)" / "(-0479)"
_STRONG_RE = re.compile(r"^\s*([hg])0*(\d+)", re.I)     # "H1", "G976"
_RFC_RE = re.compile(r"^\s*rfc\s*0*(\d+)", re.I)        # "RFC1 — Host Software"
_OEIS_RE = re.compile(r"^\s*a0*(\d+)", re.I)            # "A000001 — ..."
_PORT_RE = re.compile(r"^\s*port\s+(\d+)\s*/\s*(\w+)", re.I)  # "Port 80/tcp — http"
_TITLE_DASH_RE = re.compile(r"\s+[—–]\s+")             # em/en dash with spaces (author/name split)


def _slug(s: str, maxlen: int = 48) -> str:
    """A lowercase ascii slug — the shelf-safe form of a title or name."""
    s = unicodedata.normalize("NFKD", (s or "")).encode("ascii", "ignore").decode("ascii").lower()
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s[:maxlen].strip("_") or "_"


def _letter(s: str) -> str:
    """The single A→Z drawer a key falls in — a letter, `0-9`, or `misc`."""
    key = re.sub(r"[^a-z0-9]", "", _slug(s))
    if not key:
        return "misc"
    return "0-9" if key[0].isdigit() else key[0]


def _alpha_path(s: str) -> str:
    """A two-level A→Z shelf location `letter.pair` — the drawer, then the thumb-index tab within
    it — so one crowded letter (dictionary.s ~ 15k words) breaks into ~600-word pair-drawers. A
    single-character key repeats the letter; a digit key files under `0-9`; an empty one, `misc`."""
    key = re.sub(r"[^a-z0-9]", "", _slug(s))
    if not key:
        return "misc.misc"
    if key[0].isdigit():
        return f"0-9.{key[:2]}"
    return f"{key[0]}.{key[:2] if len(key) >= 2 else key}"


def _country_code(card: dict) -> str:
    """The 2-letter ISO country code a geography card carries in its bands (else empty)."""
    for b in (card.get("bands") or []):
        if isinstance(b, str) and len(b) == 2 and b.isalpha() and b.isupper():
            return b.lower()
    return ""


def deep_call(card: dict) -> str:
    shelf = (card.get("shelf") or "misc").strip().lower()
    title = (card.get("title") or "").strip()
    base = call_number(card)

    if shelf in ("hebrew_ot", "greek_nt"):
        m = _BOOK_REF_RE.match(title)
        if m:
            return f"{shelf}.{_slug(m.group(1), 24)}.{m.group(2)}.{m.group(3)}"
    elif shelf == "commentary":
        # box is the commentator; the title "Author on Book ch:vs" gives book (+ chapter)
        cls = (card.get("box") or "").strip().lower() or "source"
        rest = re.split(r"\s+on\s+", title, maxsplit=1)
        if len(rest) == 2:
            m = _BOOK_REF_RE.match(rest[1])
            if m:
                return f"{shelf}.{_slug(cls, 24)}.{_slug(m.group(1), 24)}.{m.group(2)}"
            return f"{shelf}.{_slug(cls, 24)}.{_slug(rest[1], 24)}"
        return f"{shelf}.{_slug(cls, 24)}"
    elif shelf == "gutenberg":
        parts = _TITLE_DASH_RE.split(title)  # "Work — Author"; author is the last segment
        if len(parts) >= 2:
            work = " ".join(parts[:-1])
            return f"{shelf}.{_slug(parts[-1], 40)}.{_slug(work, 48)}"
        return f"{shelf}.{_alpha_path(title)}.{_slug(title)}"
    elif shelf == "geography":
        cc = _country_code(card)
        if cc:  # country, then a place-name drawer so a big country (us ~ 7.5k) still walks
            return f"{shelf}.{cc}.{_letter(title)}.{_slug(title)}"
        return f"{shelf}.{_alpha_path(title)}.{_slug(title)}"
    elif shelf == "taxonomy":
        name = _TITLE_DASH_RE.split(title)[0]  # scientific name, before " — common name"
        return f"{shelf}.{_alpha_path(name)}.{_slug(name)}"
    elif shelf == "lexicon":
        m = _STRONG_RE.match(title)
        if m:
            lang, num = m.group(1).lower(), int(m.group(2))
            return f"{shelf}.{lang}{num // 1000}.{lang}{num:04d}"
    elif shelf == "history":
        m = _YEAR_TAIL_RE.search(title)
        if m:
            y = int(m.group(1))
            era = f"{(y // 100) * 100}s" if y >= 0 else f"bc_{((abs(y) + 99) // 100) * 100}s"
            return f"{shelf}.{era}.{_slug(_YEAR_TAIL_RE.sub('', title))}"
    elif shelf == "rfcs":
        m = _RFC_RE.match(title)
        if m:
            num = int(m.group(1))
            return f"{shelf}.{num // 1000}xxx.rfc{num:04d}"
    elif shelf == "oeis":
        m = _OEIS_RE.match(title)
        if m:
            num = int(m.group(1))
            return f"{shelf}.a{num // 1000:03d}xxx.a{num:06d}"
    elif shelf == "networking":
        m = _PORT_RE.match(title)  # a port list is walked by NUMBER, not by "Port…" — thousand.hundred
        if m:
            num, proto = int(m.group(1)), m.group(2).lower()
            return f"{shelf}.{num // 1000}k.{(num % 1000) // 100}c.{num:05d}_{proto}"

    # generic: a card stuck in the flat `<shelf>.source` (or bare `<shelf>`) bucket earns an
    # A→Z sublayer from its title — a dictionary/drug/food list shelved like a library.
    if base == f"{shelf}.source" or base == shelf:
        return f"{shelf}.{_alpha_path(title)}.{_slug(title)}"
    return base


# ── Facets — the controlled subjects beside the call number ──────────────────────────────────
# deep_call gives a card its PLACE (the shelf spine); facets give it its controlled SUBJECTS.
# Every structural band maps to exactly one facet TYPE; every other band folds UNDER a facet as a
# VALUE (a verse, a person, a place, a taxon), never a free top-level tag — so a filling library
# stays navigable instead of drowning in a folksonomy. Must match tools/classify_keeping's schedule.
FACET_SCHEDULE: Dict[str, List[str]] = {
    "verse":      ["chapter_verse", "cites", "citation", "cross_reference", "xref"],
    "person":     ["person", "mention_person", "father", "prophet", "apostle"],
    "place":      ["place", "mention_place", "region", "city", "geography"],
    "mention":    ["mention"],
    "sequence":   ["sequence", "prev", "next", "chapter", "section", "part"],
    "reference":  ["references", "reference", "proof_text", "proof", "citation_of"],
    "dictionary": ["dictionary", "bible_dictionary", "easton", "isbe", "smith", "vine", "thesaurus"],
    "concept":    ["concept", "scripture", "doctrine", "theme", "stoic", "virtue"],
    "taxon":      ["organism", "taxonomy", "binomial", "species", "genus"],
    "language":   ["arpabet", "phonetics", "aramaic", "transliteration", "original language"],
    "provenance": ["auto_detected", "manual", "curated", "imported"],
}
FACET_OF_BAND: Dict[str, str] = {b: f for f, _bands in FACET_SCHEDULE.items() for b in _bands}
_VERSE_FACET_RE = re.compile(
    r"^(?:[1-3]\s?)?(?:[A-Z][a-z]{1,11}\.?|Ps|Jas|Rom|Phil|Matt|Gen|Exod|Deut|Rev)"
    r"\s?\d{1,3}(?:[:.]\d{1,3})?(?:-\d{1,3})?$")
_PSALM_FACET_RE = re.compile(r"^psalm_\d+$", re.I)


def facets_for(card: dict) -> Dict[str, List[str]]:
    """The card's controlled facets — {facet_type: [values]} folded from its flat `bands` by the
    schedule. A bare value folds under a facet instead of floating: a verse ref → `verse`; a name
    co-occurring with a person/place/concept type → that facet; a token already carried by the call
    number's source (the box) → dropped as redundant; anything else → `subject` (kept, never lost).
    Must match tools/classify_keeping."""
    out: Dict[str, List[str]] = {}
    bands = card.get("bands") or []
    if not isinstance(bands, list):
        bands = [bands]
    box = (card.get("box") or "").strip().lower()
    redundant = set(box.split("_")) | ({box} if box else set())
    types: set = set()
    values: List[str] = []
    for b in bands:
        if not isinstance(b, str) or not b:
            continue
        if b in FACET_OF_BAND:
            types.add(FACET_OF_BAND[b])
        else:
            values.append(b)
    for t in types:
        out.setdefault(t, [])
    for v in values:
        if _VERSE_FACET_RE.match(v) or _PSALM_FACET_RE.match(v):
            out.setdefault("verse", []).append(v)
        elif v.lower() in redundant:
            continue
        elif "person" in types:
            out.setdefault("person", []).append(v)
        elif "place" in types:
            out.setdefault("place", []).append(v)
        elif "concept" in types:
            out.setdefault("concept", []).append(v)
        else:
            out.setdefault("subject", []).append(v)  # a named value with no clearer facet — kept
    return {k: sorted(set(v)) for k, v in out.items()}


def shelve(card: dict) -> dict:
    """Give a card its PLACE and its SUBJECTS — the Dewey call number + controlled facets — from
    what it already carries (shelf, box, title, bands). IDEMPOTENT: a card that already carries a
    call/facets is left untouched, so a pre-classified keeping pays nothing on reload. This is the
    one gate every card crosses at load (load_cards._keep) and at runtime mint (Corpus.add_card),
    so a card is shelved the moment it enters the keeping — no separate pass, no seeder to forget.
    (tools/classify_keeping is the BULK tool that re-derives and PERSISTS these into the JSONL when
    the rules change; shelve only fills what is missing.)"""
    if not card.get("call"):
        card["call"] = deep_call(card)
    if card.get("facets") is None:
        card["facets"] = facets_for(card)
    return card


def frozen_shelves() -> frozenset:
    """The shelves currently riding the shards — empty unless BOTH the env names them AND the
    shards exist (bodies are never shed without a place to rehydrate from)."""
    env = os.environ.get("CONCORDANCE_FREEZE_SHELVES", "").strip()
    if not env:
        return frozenset()
    from . import corpus_db
    if not corpus_db.available():
        return frozenset()
    return frozenset(s.strip() for s in env.split(",") if s.strip())


def rehydrate(card: Optional[dict]) -> Optional[dict]:
    """The FULL card for a frozen stub — body, bands, provenance — read from its shard.
    The resident stub is never mutated; the LIVE graph (bridges, minted edges) carries over
    the stored copy. If the shard cannot answer, the stub itself returns — id, title, and
    connections in hand, never a silent hole."""
    if not card or not card.get("frozen"):
        return card
    from . import corpus_db
    if not corpus_db.available():
        return card
    corpus_db.thaw_for(card.get("shelf") or "")
    full = corpus_db.get_card(card.get("id", ""))
    if not isinstance(full, dict):
        return card
    full["connections"] = card.get("connections", full.get("connections") or [])
    # The call number and facets are LIVE too — classified onto the resident stub AFTER the shard
    # was frozen, so the stub is authoritative and the shard's copy (if any) is stale. Carry them
    # over like the graph, so a rehydrated card (a browse brief, the /card page) shows where it sits.
    if card.get("call"):
        full["call"] = card["call"]
    if card.get("facets"):
        full["facets"] = card["facets"]
    return full


class Corpus:
    """An indexed, searchable set of cards (id -> card dict)."""

    def __init__(self, cards: Dict[str, dict], min_idf: float = MIN_DISTINCTIVE_IDF,
                 df_extra: Optional[Dict[str, int]] = None,
                 frozen_idx: Optional[Dict[str, tuple]] = None):
        self.cards = cards
        self.min_idf = min_idf
        # LAZY STUBS (increment 2): frozen cards are NOT held resident. `_frozen` maps each PUBLIC
        # frozen id -> (call, title) — a compact entry for browse and the call-tree; the full card
        # (body, connections, facets, provenance) rehydrates from the shard on read. This makes
        # resident RAM scale with `cards` (core + resident shelves), not the whole keeping (measured
        # 2026-09-26: the frozen stub dicts were ~96% of resident memory). Their document frequencies
        # ride in `_df_extra` so the corpus-wide IDF is unchanged.
        self._frozen: Dict[str, tuple] = dict(frozen_idx) if frozen_idx else {}
        # Built WITH freeze awareness (default_corpus / load_cards pass an index, empty or not) vs a
        # fixture `Corpus({...})` that never shed anything: only the former may merge shard freight.
        # The distinction is the ARGUMENT's presence, not the index's size — a shard-only node whose
        # resident keeping is empty still freezes, and must still read its shards.
        self._froze: bool = frozen_idx is not None
        self._by_token: Dict[str, List[str]] = {}
        self._df_extra: Dict[str, int] = dict(df_extra) if df_extra else {}
        for cid, c in cards.items():
            if not is_public(c):
                continue
            for t in set(_tokens(_card_text(c))):
                self._by_token.setdefault(t, []).append(cid)
        # CANONICAL POSTINGS — sorted once at load so ranking is a function of the cards + query, not
        # insertion order (invariant I of tests/test_retrieval_invariants.py).
        for v in self._by_token.values():
            v.sort()
        # N = the whole public keeping: resident public cards + the frozen index (all public), so IDF
        # is unchanged by freezing.
        self._n = max(1, sum(1 for c in cards.values() if is_public(c)) + len(self._frozen))

        # THE CALL-NUMBER INDEX — an instant walk over the whole keeping, built from resident public
        # cards AND the frozen index (each frozen id carries its (call, title)). `_call_tree` is nested
        # {seg: {"n", "kids"}}; `_cids_by_call` groups ids by full call; `_public_sorted` is every
        # public id pre-sorted for O(page) top-level paging. Frozen ids resolve their call/title via
        # `_call_of`/`_title_of` (resident dict OR the compact index).
        self._call_tree: Dict[str, dict] = {}
        self._cids_by_call: Dict[str, List[str]] = {}

        def _add(cid: str, call: str) -> None:
            self._cids_by_call.setdefault(call, []).append(cid)
            node = self._call_tree
            for seg in call.split("."):
                entry = node.setdefault(seg, {"n": 0, "kids": {}})
                entry["n"] += 1
                node = entry["kids"]

        for cid, c in cards.items():
            if not is_public(c):
                continue
            call = c.get("call") or deep_call(c)
            c["call"] = call
            _add(cid, call)
        # Frozen ids join the call-tree, and their per-shelf tally is banked in the SAME pass so
        # reader-facing counts (deck sizes, the Floor measure) can include the frozen bulk without a
        # scan — the whole keeping shows, not just what stayed resident.
        self._frozen_shelf_counts: Dict[str, int] = {}
        for cid, fz in self._frozen.items():
            call = (fz[0] if fz else "") or "misc"
            _add(cid, call)
            sh = call.split(".")[0]
            self._frozen_shelf_counts[sh] = self._frozen_shelf_counts.get(sh, 0) + 1
        for v in self._cids_by_call.values():
            v.sort()
        self._public_sorted: List[str] = sorted(
            (cid for cids in self._cids_by_call.values() for cid in cids),
            key=lambda cid: (self._call_of(cid), self._title_of(cid)))

    def _call_of(self, cid: str) -> str:
        c = self.cards.get(cid)
        if c is not None:
            return c.get("call") or ""
        fz = self._frozen.get(cid)
        return (fz[0] if fz else "") or ""

    def _title_of(self, cid: str) -> str:
        c = self.cards.get(cid)
        if c is not None:
            return c.get("title") or cid
        fz = self._frozen.get(cid)
        return (fz[1] if fz else cid) or cid

    def has(self, cid: str) -> bool:
        """Is this a card the corpus knows — resident OR a frozen index entry?"""
        return cid in self.cards or cid in self._frozen

    def frozen_shelf_counts(self) -> Dict[str, int]:
        """Public cards on frozen shelves, counted per shelf (from the compact index, precomputed at
        load). Reader-facing measures add this to the resident tally so the whole keeping is shown."""
        return dict(self._frozen_shelf_counts)

    def _shelf_of(self, cid: str) -> str:
        c = self.cards.get(cid)
        if c is not None:
            return (c.get("shelf") or "").lower()
        # a frozen card's shelf is the head of its Dewey call ("shelf.class.item")
        call = self._call_of(cid)
        return call.split(".")[0] if call else ""

    def _surface_of(self, cid: str) -> str:
        c = self.cards.get(cid)
        if c is not None:
            return c.get("surface") or "?"
        fz = self._frozen.get(cid)
        return (fz[2] if fz and len(fz) > 2 else "?") or "?"

    def full(self, cid: str) -> Optional[dict]:
        """The FULL card by id — resident, or rehydrated from the shard for a frozen id (lazy stubs).
        None if unknown. is_public is NOT applied here (callers decide); the frozen index holds only
        public cards, and resident cards keep their own flags."""
        c = self.cards.get(cid)
        if c is not None:
            return rehydrate(c)
        if cid in self._frozen:
            # rehydrate thaws the frozen card's shard, reads the full card, and falls back to this
            # minimal stub if the shard cannot answer (never a silent hole).
            return rehydrate({"id": cid, "shelf": self._shelf_of(cid), "frozen": True,
                              "title": self._title_of(cid)})
        return None

    def _call_node(self, prefix: str) -> Optional[dict]:
        node = self._call_tree
        entry = None
        for seg in (prefix.split(".") if prefix else []):
            entry = node.get(seg)
            if entry is None:
                return None
            node = entry["kids"]
        return entry

    def call_children(self, prefix: str = "") -> List[tuple]:
        """The next level of the call tree under `prefix` — [(full_call, count)], most first. Instant."""
        if not prefix:
            return sorted(((seg, e["n"]) for seg, e in self._call_tree.items()), key=lambda x: -x[1])
        entry = self._call_node(prefix)
        if entry is None:
            return []
        return sorted(((prefix + "." + seg, e["n"]) for seg, e in entry["kids"].items()), key=lambda x: -x[1])

    def call_total(self, prefix: str = "") -> int:
        if not prefix:
            return sum(e["n"] for e in self._call_tree.values())
        entry = self._call_node(prefix)
        return entry["n"] if entry else 0

    def cids_for_call(self, prefix: str) -> List[str]:
        """Card ids at or under a call prefix, in stable order — gathered from the grouped index
        (bounded by the number of distinct call numbers, not the size of the keeping)."""
        p = (prefix or "").strip().lower().rstrip(".")
        out: List[str] = []
        for call, cids in self._cids_by_call.items():
            if call == p or call.startswith(p + "."):
                out.extend(cids)
        out.sort(key=lambda cid: (self._call_of(cid), self._title_of(cid)))
        return out

    def footprint(self, sample: int = 400) -> Dict[str, Any]:
        """What this corpus costs in memory, BY STRUCTURE — measured, not believed.

        Matt, 2026-08-01, questioning the freeze: *"The concept is we keep the corpus frozen and
        only unthaw and carry what is necessary, but that may be a faulty concept."*

        Freezing 24 shelves took each engine from ~2.8 GB to ~1.7 GB, so it worked — but 25,087
        resident cards costing 1.7 GB is ~68 KB PER CARD, which no card body explains. That points
        at the index rather than the text, and the difference decides an architecture: if the
        weight is `_by_token`, moving bodies to shards treated a symptom and one on-disk store
        would be both smaller and simpler. If it is `cards`, freezing is doing exactly its job.

        A belief cannot settle that. This can, from the live process, without loading anything.

        SAMPLED, AND IT SAYS SO. Walking 25,000 nested dicts on a serving box is not free, so the
        card cost is measured over `sample` of them and scaled — the returned record carries the
        sample size and the population so nobody reads an estimate as a census.
        """
        import sys as _sys

        def _deep(obj, _seen=None) -> int:
            """Recursive size of a small object graph — dicts, lists and strings, no cycles here."""
            _seen = _seen if _seen is not None else set()
            if id(obj) in _seen:
                return 0
            _seen.add(id(obj))
            total = _sys.getsizeof(obj)
            if isinstance(obj, dict):
                for k, v in obj.items():
                    total += _deep(k, _seen) + _deep(v, _seen)
            elif isinstance(obj, (list, tuple, set)):
                for x in obj:
                    total += _deep(x, _seen)
            return total

        ids = list(self.cards)
        n_cards = len(ids)
        taken = ids[:max(1, min(sample, n_cards))]
        per_card = (sum(_deep(self.cards[i]) for i in taken) / len(taken)) if taken else 0
        cards_bytes = int(per_card * n_cards)

        # The inverted index: token -> [card_id, ...]. The POSTINGS are the thing to count — every
        # one is a pointer in a list, and the lists themselves carry per-object overhead.
        postings = sum(len(v) for v in self._by_token.values())
        idx_bytes = _sys.getsizeof(self._by_token)
        idx_bytes += sum(_sys.getsizeof(t) + _sys.getsizeof(v) for t, v in
                         list(self._by_token.items())[:sample])
        if len(self._by_token) > sample:
            idx_bytes = int(idx_bytes / max(1, min(sample, len(self._by_token)))
                            * len(self._by_token))
        idx_bytes += postings * 8                      # one pointer per posting

        df_bytes = _sys.getsizeof(self._df_extra) + sum(
            _sys.getsizeof(k) + 28 for k in list(self._df_extra)[:sample])

        return {
            "cards": n_cards, "tokens": len(self._by_token), "postings": postings,
            "df_extra_tokens": len(self._df_extra),
            "bytes": {"cards": cards_bytes, "token_index": idx_bytes, "df_extra": df_bytes,
                      "total": cards_bytes + idx_bytes + df_bytes},
            "mb": {"cards": round(cards_bytes / 1048576, 1),
                   "token_index": round(idx_bytes / 1048576, 1),
                   "df_extra": round(df_bytes / 1048576, 1),
                   "total": round((cards_bytes + idx_bytes + df_bytes) / 1048576, 1)},
            "measured_over": len(taken), "population": n_cards,
            "note": "card cost is sampled and scaled; index cost is counted postings + sampled "
                    "key/list overhead. An estimate, and labelled as one.",
        }

    def add_card(self, card: dict) -> None:
        """Insert one card into the live corpus AND its token index — so a just-minted
        verification is searchable immediately, no restart. Idempotent by id."""
        cid = card.get("id")
        if not cid:
            return
        shelve(card)  # a live-minted card is shelved like any other (walkable on next reload)
        self.cards[cid] = card
        if is_public(card):
            for t in set(_tokens(_card_text(card))):
                self._by_token.setdefault(t, [])
                if cid not in self._by_token[t]:
                    self._by_token[t].append(cid)
            self._n = max(1, sum(1 for c in self.cards.values() if is_public(c)) + len(self._frozen))
            # a live-minted card is also walkable: place it in the call-tree now (frozen ids already
            # entered it at load). Idempotent-ish — a re-mint of the same id re-adds; acceptable for
            # the rare live mint, and a reload rebuilds the tree cleanly.
            call = card.get("call") or deep_call(card)
            card["call"] = call
            if cid not in self._cids_by_call.get(call, ()):
                self._cids_by_call.setdefault(call, []).append(cid)

    def _index_card_ids(self) -> set:
        ids: set = set()
        for cids in self._by_token.values():
            ids.update(cids)
        return ids

    def _idf(self, query_tokens: set) -> Dict[str, float]:
        return {t: max(0.0, math.log(self._n / (len(self._by_token.get(t, ()))
                                                + self._df_extra.get(t, 0) + 1)))
                for t in query_tokens}

    def _candidates(self, query_tokens: set, max_candidates: int = 600,
                    seat_family: Optional[set] = None) -> List[str]:
        """Candidate cards, RAREST TOKENS FIRST — the cap must never starve the subject.

        This was a heisenbug that survived every gate: tokens were taken in SET-ITERATION order,
        which is hash-seed dependent and re-rolls on every process restart. For "southern
        baptists" (df 2,702 vs 160), whichever token iterated first flooded the 600-candidate cap
        — one restart returned 8 Baptist histories, the next restart returned 1, for the same
        query on the same corpus. A ranking that changes with a restart is a ranking that cannot
        be trusted or tested. Iterating by ascending document frequency is deterministic and puts
        the words the question is actually about beyond starvation: a common word can never crowd
        out a rare one, only fill the seats the rare ones left.
        """
        counts: Dict[str, int] = {}
        exempt = set(seat_family or ())
        for qt in sorted(query_tokens, key=lambda t: (self._df(t) or 10**9, t)):
            uncapped = qt in exempt
            for cid in self._by_token.get(qt, []):
                if cid in counts:
                    counts[cid] += 1          # a seated card still collects its later matches
                elif uncapped or len(counts) < max_candidates:
                    counts[cid] = 1
        # THE SEAT IS NEVER CAPPED. The cap is a performance guard for common-word floods; the
        # partition's upper tier is DEFINED by holding the seat, so every seat-holder must reach
        # scoring or the tier lies by omission. Found when canonical (id-sorted) postings made
        # cap admission an alphabetical lottery and the survival how-to card lost it inside its
        # own token. Worst case is scoring one common seat's full postings (~the resident corpus,
        # 25k short texts) — the price of a tier that tells the truth.
        return sorted(counts, key=lambda x: -counts[x])

    def _df(self, token: str) -> int:
        return len(self._by_token.get(token, ())) + self._df_extra.get(token, 0)

    def _present_form(self, token: str) -> str:
        """The form of this word the corpus ACTUALLY CONTAINS — naive singular/plural only.

        "Southern Baptists" returned nothing from a library full of Baptist material, because
        there is no stemming anywhere: the subject partition demanded the exact token "baptists",
        the corpus says "baptist", and _idf hands an UNSEEN token the highest rarity of all —
        df=0 is the rarest thing there is — so the absent plural won the subject seat and then
        partitioned out the entire keeping. An empty shelf reported by a full library.

        Only trailing-s/es variants, only when the token itself is absent, and only toward a form
        that exists: anything cleverer is a stemmer, and a stemmer quietly rewrites what the
        person asked.
        """
        if self._df(token) > 0 or len(token) < 4:
            return token
        candidates = [token + "s", token + "es"]
        if token.endswith("es"):
            candidates.append(token[:-2])
        if token.endswith("s"):
            candidates.append(token[:-1])
        for v in candidates:
            if len(v) >= 3 and self._df(v) > 0:
                return v
        return token

    def _with_variants(self, query_tokens: set) -> set:
        """Query tokens plus BOTH numbers of each, wherever that form exists in the index.

        The first version added a variant only when the asked form was ABSENT (df=0) — which left
        a hole measured live on 2026-08-02: "methodists" has df=31, so no "methodist" was added,
        `common = query ∩ doc` came up empty against the singular-only Methodist / Wesleyan voice
        card, and the card died at the no-common-tokens gate BEFORE the family partition could
        fire. The partition can only judge what scoring lets through, so the family has to enter
        at the tokens, not just at the verdict. Only forms the index actually contains are added —
        expansion never invents a word the corpus has never seen.
        """
        out = set(query_tokens)
        for t in query_tokens:
            out.add(self._present_form(t))
            for v in self.subject_family(t):
                if self._df(v) > 0:
                    out.add(v)
        return out

    @staticmethod
    def subject_family(subject: Optional[str]) -> set:
        """The subject in both numbers — "methodists" and "methodist" are one subject.

        The partition demanded the exact subject form, so the Methodist / Wesleyan voice card
        (which says "Methodist", singular) was partitioned OUT of a search for "methodists" —
        live, on a shelf that plainly holds the tradition. A card about the singular IS about the
        plural. Trailing s/es only; anything cleverer is a stemmer.
        """
        if not subject:
            return set()
        fam = {subject, subject + "s"}
        if subject.endswith("es") and len(subject) > 4:
            fam.add(subject[:-2])
        if subject.endswith("s") and len(subject) > 3:
            fam.add(subject[:-1])
        return fam

    def _subject_of(self, query_tokens: set, idf: Dict[str, float]) -> Optional[str]:
        """The rarest query word — what the question is ACTUALLY about.

        "Wesleyan Church" is about Wesleyans. "Church" is in half the library. And the seat must
        be held by a form the corpus CONTAINS: an absent token has df=0, which _idf reads as
        maximal rarity, so without the present-form step a typo or a plural would always win the
        seat and then partition out everything (the Southern Baptists failure).
        """
        if not query_tokens:
            return None
        chosen = max(query_tokens, key=lambda t: idf.get(t, 0.0))
        return self._present_form(chosen)

    def _score(self, card: dict, query_tokens: set, idf: Dict[str, float],
               subject: Optional[str] = None) -> float:
        """TF-IDF over the card text — with a HARD PARTITION on the subject word.

        Matt, 2026-08-01, on asking for the Wesleyan Church: *"It currently gives a bunch of not
        useful information... just random cards. Right now it's a dud."* He was right, and the
        cause was here.

        The score is sum(tf x idf) / log(len). TERM FREQUENCY OF A COMMON WORD OVERWHELMS THE
        PRESENCE OF A RARE ONE: a treatise that says "church" forty times outscores a card that
        says "Wesleyan" once. So "Wesleyan Church" returned Belgic Article 29 and Heidelberg Q85 —
        REFORMED confessions — to someone asking about a Wesleyan church. Not merely irrelevant:
        it hands a reader the tradition that disagrees with theirs, on the points they care about.
        And because the connection cloud then builds around the top hit, the whole neighbourhood
        came back Reformed. One bad first card poisons everything downstream.

        A WEIGHT WOULD NOT FIX THIS — any multiplier can be out-shouted by enough repetitions.
        This is a PARTITION: a card that does not contain the subject word cannot outrank one that
        does, however often it repeats the rest. The shape decides, not a tuned constant, so no
        amount of term frequency can reverse the flow. `SUBJECT_TIER` is larger than any reachable
        TF-IDF score by construction, which makes the two tiers non-overlapping.

        A one-word query is its own subject, so this changes nothing there.
        """
        doc_tokens = _tokens(_card_text(card))
        if not doc_tokens:
            return 0.0
        common = query_tokens & set(doc_tokens)
        if not common:
            return 0.0
        if max((idf.get(t, 0.0) for t in common), default=0.0) < self.min_idf:
            return 0.0
        counts = {t: 0 for t in common}
        for t in doc_tokens:
            if t in counts:
                counts[t] += 1
        # A frozen stub's text is its TITLE alone — scoring it by its real (tiny) length would
        # hand it an artificial length-normalization boost over full resident cards (caught by
        # the probe battery: gutenberg title stubs outscored the Bible-facts answerer). Score
        # stubs against a typical FULL card's document length instead, so freezing a shelf
        # never changes its cards' rank.
        doc_len = max(len(doc_tokens), 150) if card.get("frozen") else len(doc_tokens)
        score = sum(counts[t] * idf.get(t, 0.0) for t in common) / math.log(doc_len + 10)
        if len(common) == len(query_tokens):
            score *= 1.5
        # SUBSTANCE VS HEADWORD. Applied to the BASE score, before the tier addition below, so it
        # only ever reorders cards WITHIN whichever tier they already earned: a boosted stub still
        # cannot cross into the subject tier alone (base scores never approach SUBJECT_TIER's
        # scale — see its own comment), and among cards that already hold the subject, a real
        # answer now pulls ahead of a bare pointer that merely names it. A frozen card scored here
        # BEFORE rehydration still carries its true (stripped) stub body, so this correctly treats
        # it as a stub on that first pass; `search()` rehydrates and re-scores any frozen card that
        # clears zero, so the score actually used for ranking always reflects the real body.
        if len(str(card.get("body") or "")) >= STUB_BODY_CHARS:
            score *= SUBSTANCE_WEIGHT
        # THE PARTITION. Holding the subject word puts a card in the upper tier outright —
        # in EITHER number: a card that says "Methodist" is about "methodists" (the singular-only
        # voice card was partitioned out of a plural search, live, 2026-08-02). The seat is
        # chosen among the ASKED words, never among expansion variants — a rare junk variant
        # ("southerns") once stole the seat from "baptists". Search computes it once and passes
        # it in; never an instance attribute, because searches run concurrently across threads.
        if subject is None:
            subject = self._subject_of(query_tokens, idf)
        if subject and (self.subject_family(subject) & set(doc_tokens)):
            score += SUBJECT_TIER
        return float(score)

    def search(self, query: str, limit: int = 25, include_witness: bool = True,
               shelves: Optional[set] = None) -> List[dict]:
        """Ranked search over the keeping.

        The keeping is ONE SHARED library: by default BOTH surfaces draw the whole thing
        — the .com includes the religious cards too (Matt, 2026-06-26: "the religious
        cards can be included"; "we are not hiding anything"). `include_witness=False`
        gives an optional scrubbed view if a caller ever wants secular-only results.

        `shelves` (a set) restricts the search to those shelves — the DECK fast-path (the Hare):
        scoring only the deck's cards instead of the whole keeping. None = the whole library
        (the Tortoise). A deck search that comes up short can always fall back to the full one."""
        # A truthy non-string query (e.g. an int from an uncoerced MCP tool call — args.get("query")
        # with no str() at the call site) would otherwise crash here: "query or ''" only substitutes
        # the fallback for a FALSY query, so a non-empty int/list survives and .lower() raises
        # AttributeError deep inside _tokens(). This is the one shared search entry point (the HTTP
        # /search route and /ask already coerce before calling in, but the MCP search tool does not)
        # — coerce once, here, so every caller is safe regardless of what reaches this function.
        query = str(query) if query else ""
        # STOPWORDS ARE NOT A SUBJECT — the same rule as the shard matcher, from the same list, so
        # the two doors can never drift apart.
        #
        # IDF alone does NOT solve this, which is why the bug survived here after the shard side was
        # fixed. `_idf` is log(n / (df + 1)): a word in 20k of 478k cards still scores ~3.2, small
        # next to a rare term but very far from zero. So when the DISTINCTIVE word matches nothing
        # — "what is Mahavira", and we hold no Mahavira — the only tokens left contributing are
        # "what" and "is", cards containing them score above zero, and the reader is handed Marcus
        # Aurelius as though it were an answer. Measured live 2026-08-01 on the 1,000-probe assay.
        #
        # A gap must be allowed to report itself; a miss is what feeds the want list. Dropping the
        # stopwords before candidates or scoring means nothing can be retrieved on their strength
        # alone. A query made only of stopwords asks about nothing and returns nothing.
        from .corpus_db import _STOP          # one list, both matchers (corpus_db imports nothing here)
        asked = {t for t in _tokens(query) if t not in _STOP}
        # THE PRESENT FORM RIDES ALONG — for scoring. The SUBJECT SEAT is chosen among the words
        # actually ASKED: expansion once added "southerns" (a rare variant of a common word,
        # df tiny so idf huge) and the junk variant stole the seat from "baptists". Variants
        # widen what can match; they never redefine what the question is about.
        query_tokens = self._with_variants(asked)
        # the seat belongs to the words actually asked — computed once, passed to scoring;
        # never instance state (searches run concurrently across handler threads)
        seat = self._subject_of(asked, self._idf(asked)) if asked else None
        if not query_tokens:
            return []
        idf = self._idf(query_tokens)
        # exact-match targets: the query as typed, and its canonical verse forms — so a verse
        # lookup ("Philippians 4:13", the most common human search) ranks the verse card first
        # instead of a fuzzy book match. Reuses the growth engine's one verse canonicalizer.
        from . import growth as _growth
        qn = " ".join((query or "").lower().split())
        q_exact = {qn} | {r.lower() for r in _growth.refs_in_text(query or "")}
        from . import stigmergy as _stig     # the pheromone layer (gated OFF by default → boost is 1.0)
        from . import repellent as _rep       # the no-entry pheromone (gated OFF → damp is 1.0)
        from . import alignment as _align     # gate the keeping by agreement (gated OFF → keep, damp = True, 1.0)
        align_ctx = _align.context(query)     # the subjects the query explicitly names (empty when off)
        scored = []

        def _finalize(c: dict, s: float) -> float:
            """The exact-title / survival / theory boosts — applied IDENTICALLY to a resident
            candidate and to a frozen hit pulled from the shard, so the two sources rank on one
            scale. Boosts multiply the base score, so they only reorder WITHIN the tier a card
            already earned; they can never smuggle an off-subject hit into the subject tier.

            The pronunciation guard: a pron card's title IS its headword for all ~125k of them, so
            an exact-title match is an INDEX COLLISION, not evidence of definitiveness (without it
            every one-word lookup led with an ARPABET string, live 2026-09-03). Verse/named-work
            exact-title cards ARE the answer and keep the boost."""
            title_n = " ".join(str(c.get("title", "")).lower().split())
            ref_n = " ".join(str((c.get("source") or {}).get("ref", "")).lower().split())
            if c.get("shelf") != "pronunciation":
                if title_n in q_exact or (ref_n and ref_n in q_exact and title_n in q_exact):
                    s *= 9.0                          # THE card for this exact reference/title
                elif q_exact and (title_n in q_exact or ref_n in q_exact):
                    s *= 4.0
            if c.get("shelf") == "survival" and (_PRACTICAL & query_tokens):
                s *= 3.0                              # a how-to question prefers the field library
            elif c.get("shelf") == "theories":
                s *= THEORY_WEIGHT                     # a theory is load-bearing (Matt 2026-08-02)
            # STIGMERGY (ants): a well-travelled trail leads WITHIN its tier — multiplies the base
            # score like the boosts above, capped, so it never crosses tiers. 1.0 when gated off.
            s *= _stig.boost_factor(c.get("id"))
            # REPELLENT (no-entry pheromone): a source discernment judged leads-astray is down-weighted
            # WITHIN its tier, so it stops crowding queries it does not answer. 1.0 when gated off, and
            # floored (never zeroed) — a repelled card stays retrievable for discernment.
            s *= _rep.damp_factor(c.get("id"))
            return s

        for cid in self._candidates(
                query_tokens, seat_family=(self.subject_family(seat) if seat else None)):
            c = self.cards.get(cid)
            if not c or not is_public(c):
                continue
            if not include_witness and c.get("surface") == "witness":
                continue
            if shelves is not None and c.get("shelf") not in shelves:
                continue
            s = self._score(c, query_tokens, idf, subject=seat)
            if s > 0:
                keep, damp = _align.verdict(c, align_ctx)   # gate by agreement (no-op when off)
                if keep:
                    scored.append((_finalize(c, s) * damp, c))

        # FROZEN FREIGHT RIDES THE SHARD, SCORED ON ONE SCALE. Frozen shelves are no longer in the
        # resident index, so their hits come from the shard FTS (which indexes the full text) and are
        # scored through the SAME `_score` + `_finalize` as resident cards — interleaved by score, not
        # appended as a fallback. This is what lets `_by_token` shed ~500k title stubs (the measured
        # 69% of resident RAM) with no ranking change: a frozen card is scored on its real body here,
        # exactly as the old title-match→rehydrate→re-score path did. Skipped entirely when nothing is
        # frozen (frozen_shelves() is empty), so an unfrozen corpus is byte-for-byte unchanged.
        # AND skipped for a corpus that holds no frozen index of its own (2026-10-02): the env names
        # the shelves, but only a corpus BUILT with `frozen_idx` shed them to the shard. A fixture
        # corpus (`Corpus({...})` in a test) under the servers' env was receiving the live keeping's
        # shard hits — real dictionary cards outranking the fixture's own — which is not a ranking
        # bug, it is freight from a shard this corpus never loaded.
        frozen = frozen_shelves() if self._froze else frozenset()
        if frozen and (shelves is None or (set(shelves) & frozen)):
            from . import corpus_db
            corpus_db.thaw_for(*frozen)
            have = {c.get("id") for _s, c in scored}
            for hit in corpus_db.search(query, limit=max(int(limit) * 3, 60),
                                        include_witness=include_witness):
                sh = hit.get("shelf")
                if sh not in frozen or hit.get("id") in have or not is_public(hit):
                    continue                          # resident shelves are already fully scored
                if shelves is not None and sh not in shelves:
                    continue
                s = self._score(hit, query_tokens, idf, subject=seat)
                if s <= 0:
                    continue
                keep, damp = _align.verdict(hit, align_ctx)   # gate by agreement (no-op when off)
                if not keep:
                    continue
                scored.append((_finalize(hit, s) * damp, hit))
                have.add(hit.get("id"))
        # a TOTAL order: equal scores tie-break on id, so the ranking is a function of the
        # cards and the query alone — never of construction order (invariant I)
        scored.sort(key=lambda x: (-x[0], str(x[1].get("id") or "")))

        # NEVER PAD THE TAIL WITH CARDS THAT MISS THE SUBJECT. The partition put subject-holders
        # in the upper tier, but ranking alone still let the leftovers fill the limit: live,
        # "Wesleyan Church" came back with six Wesleyan cards and then a Kensington church
        # directory and "Doctrines Objected to in the Church of Rome" at 7 and 8, purely to reach
        # eight. Padding a count with things a reader must discard is the same lie as a silent cap
        # — it reads as "here is what we hold" when two of them are noise.
        #
        # So when ANY card holds the subject word, only those are served. Six true results beat
        # eight with two lies, and the count then means what it says. (The shard merge already
        # excludes rather than demotes; this makes both halves of the rule behave alike, which
        # they did not, and that inconsistency is what reached the reader.)
        if scored and scored[0][0] >= SUBJECT_TIER:
            scored = [(s, c) for s, c in scored if s >= SUBJECT_TIER]
        out = [c for _s, c in scored[:max(1, int(limit))]]
        # STIGMERGY DEPOSIT (gated OFF → no-op): the cards this search returned proved retrieval-worthy,
        # so lay a little pheromone on them — aggregate, no identity, no query. Trails that serve
        # strengthen; the evaporation in the module fades the rest.
        _stig.deposit(c.get("id") for c in out)
        return out


