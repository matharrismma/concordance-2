def frozen_shelves() -> frozenset:
    """The shelves currently riding the shards — empty unless BOTH the env names them AND the
    shards exist (bodies are never shed without a place to rehydrate from)."""
    env = os.environ.get("CONCORDANCE_FREEZE_SHELVES", "").strip()
    if not env:
        return frozenset()
    from . import corpus_db
    if not corpus_db.available():
        return frozenset()
    return frozenset(s.strip() for s in env.split(",") if s.strip())


def rehydrate(card: Optional[dict]) -> Optional[dict]:
    """The FULL card for a frozen stub — body, bands, provenance — read from its shard.
    The resident stub is never mutated; the LIVE graph (bridges, minted edges) carries over
    the stored copy. If the shard cannot answer, the stub itself returns — id, title, and
    connections in hand, never a silent hole."""
    if not card or not card.get("frozen"):
        return card
    from . import corpus_db
    if not corpus_db.available():
        return card
    corpus_db.thaw_for(card.get("shelf") or "")
    full = corpus_db.get_card(card.get("id", ""))
    if not isinstance(full, dict):
        return card
    full["connections"] = card.get("connections", full.get("connections") or [])
    return full


class Corpus:
    """An indexed, searchable set of cards (id -> card dict)."""

    def __init__(self, cards: Dict[str, dict], min_idf: float = MIN_DISTINCTIVE_IDF,
                 df_extra: Optional[Dict[str, int]] = None):
        self.cards = cards
        self.min_idf = min_idf
        self._by_token: Dict[str, List[str]] = {}
        # extra document frequency from frozen stubs' full text (streamed out of load_cards) —
        # the tokens themselves live on the shard, but their COUNTS stay here so the corpus-wide
        # IDF statistics are identical whether a shelf is frozen or resident
        self._df_extra: Dict[str, int] = dict(df_extra) if df_extra else {}
        for cid, c in cards.items():
            if not is_public(c):
                continue
            for t in set(_tokens(_card_text(c))):
                self._by_token.setdefault(t, []).append(cid)
        # CANONICAL POSTINGS. Two corpora over the same cards must rank identically whatever
        # order the cards arrived in — invariant I of tests/test_retrieval_invariants.py. Without
        # this, cap admission and tie order both follow insertion order, and "same corpus, same
        # query" can rank differently across builds. Sorted once at load; never at query time.
        for v in self._by_token.values():
            v.sort()
        self._n = max(1, len(self._index_card_ids()))

    def footprint(self, sample: int = 400) -> Dict[str, Any]:
        """What this corpus costs in memory, BY STRUCTURE — measured, not believed.

        Matt, 2026-08-01, questioning the freeze: *"The concept is we keep the corpus frozen and
        only unthaw and carry what is necessary, but that may be a faulty concept."*

        Freezing 24 shelves took each engine from ~2.8 GB to ~1.7 GB, so it worked — but 25,087
        resident cards costing 1.7 GB is ~68 KB PER CARD, which no card body explains. That points
        at the index rather than the text, and the difference decides an architecture: if the
        weight is `_by_token`, moving bodies to shards treated a symptom and one on-disk store
        would be both smaller and simpler. If it is `cards`, freezing is doing exactly its job.

        A belief cannot settle that. This can, from the live process, without loading anything.

        SAMPLED, AND IT SAYS SO. Walking 25,000 nested dicts on a serving box is not free, so the
        card cost is measured over `sample` of them and scaled — the returned record carries the
        sample size and the population so nobody reads an estimate as a census.
        """
        import sys as _sys

        def _deep(obj, _seen=None) -> int:
            """Recursive size of a small object graph — dicts, lists and strings, no cycles here."""
            _seen = _seen if _seen is not None else set()
            if id(obj) in _seen:
                return 0
            _seen.add(id(obj))
            total = _sys.getsizeof(obj)
            if isinstance(obj, dict):
                for k, v in obj.items():
                    total += _deep(k, _seen) + _deep(v, _seen)
            elif isinstance(obj, (list, tuple, set)):
                for x in obj:
                    total += _deep(x, _seen)
            return total

        ids = list(self.cards)
        n_cards = len(ids)
        taken = ids[:max(1, min(sample, n_cards))]
        per_card = (sum(_deep(self.cards[i]) for i in taken) / len(taken)) if taken else 0
        cards_bytes = int(per_card * n_cards)

        # The inverted index: token -> [card_id, ...]. The POSTINGS are the thing to count — every
        # one is a pointer in a list, and the lists themselves carry per-object overhead.
        postings = sum(len(v) for v in self._by_token.values())
        idx_bytes = _sys.getsizeof(self._by_token)
        idx_bytes += sum(_sys.getsizeof(t) + _sys.getsizeof(v) for t, v in
                         list(self._by_token.items())[:sample])
        if len(self._by_token) > sample:
            idx_bytes = int(idx_bytes / max(1, min(sample, len(self._by_token)))
                            * len(self._by_token))
        idx_bytes += postings * 8                      # one pointer per posting

        df_bytes = _sys.getsizeof(self._df_extra) + sum(
            _sys.getsizeof(k) + 28 for k in list(self._df_extra)[:sample])

        return {
            "cards": n_cards, "tokens": len(self._by_token), "postings": postings,
            "df_extra_tokens": len(self._df_extra),
            "bytes": {"cards": cards_bytes, "token_index": idx_bytes, "df_extra": df_bytes,
                      "total": cards_bytes + idx_bytes + df_bytes},
            "mb": {"cards": round(cards_bytes / 1048576, 1),
                   "token_index": round(idx_bytes / 1048576, 1),
                   "df_extra": round(df_bytes / 1048576, 1),
                   "total": round((cards_bytes + idx_bytes + df_bytes) / 1048576, 1)},
            "measured_over": len(taken), "population": n_cards,
            "note": "card cost is sampled and scaled; index cost is counted postings + sampled "
                    "key/list overhead. An estimate, and labelled as one.",
        }

    def add_card(self, card: dict) -> None:
        """Insert one card into the live corpus AND its token index — so a just-minted
        verification is searchable immediately, no restart. Idempotent by id."""
        cid = card.get("id")
        if not cid:
            return
        self.cards[cid] = card
        if is_public(card):
            for t in set(_tokens(_card_text(card))):
                self._by_token.setdefault(t, [])
                if cid not in self._by_token[t]:
                    self._by_token[t].append(cid)
            self._n = max(1, len(self._index_card_ids()))

    def _index_card_ids(self) -> set:
        ids: set = set()
        for cids in self._by_token.values():
            ids.update(cids)
        return ids

    def _idf(self, query_tokens: set) -> Dict[str, float]:
        return {t: max(0.0, math.log(self._n / (len(self._by_token.get(t, ()))
                                                + self._df_extra.get(t, 0) + 1)))
                for t in query_tokens}

    def _candidates(self, query_tokens: set, max_candidates: int = 600,
                    seat_family: Optional[set] = None) -> List[str]:
        """Candidate cards, RAREST TOKENS FIRST — the cap must never starve the subject.

        This was a heisenbug that survived every gate: tokens were taken in SET-ITERATION order,
        which is hash-seed dependent and re-rolls on every process restart. For "southern
        baptists" (df 2,702 vs 160), whichever token iterated first flooded the 600-candidate cap
        — one restart returned 8 Baptist histories, the next restart returned 1, for the same
        query on the same corpus. A ranking that changes with a restart is a ranking that cannot
        be trusted or tested. Iterating by ascending document frequency is deterministic and puts
        the words the question is actually about beyond starvation: a common word can never crowd
        out a rare one, only fill the seats the rare ones left.
        """
        counts: Dict[str, int] = {}
        exempt = set(seat_family or ())
        for qt in sorted(query_tokens, key=lambda t: (self._df(t) or 10**9, t)):
            uncapped = qt in exempt
            for cid in self._by_token.get(qt, []):
                if cid in counts:
                    counts[cid] += 1          # a seated card still collects its later matches
                elif uncapped or len(counts) < max_candidates:
                    counts[cid] = 1
        # THE SEAT IS NEVER CAPPED. The cap is a performance guard for common-word floods; the
        # partition's upper tier is DEFINED by holding the seat, so every seat-holder must reach
        # scoring or the tier lies by omission. Found when canonical (id-sorted) postings made
        # cap admission an alphabetical lottery and the survival how-to card lost it inside its
        # own token. Worst case is scoring one common seat's full postings (~the resident corpus,
        # 25k short texts) — the price of a tier that tells the truth.
        return sorted(counts, key=lambda x: -counts[x])

    def _df(self, token: str) -> int:
        return len(self._by_token.get(token, ())) + self._df_extra.get(token, 0)

    def _present_form(self, token: str) -> str:
        """The form of this word the corpus ACTUALLY CONTAINS — naive singular/plural only.

        "Southern Baptists" returned nothing from a library full of Baptist material, because
        there is no stemming anywhere: the subject partition demanded the exact token "baptists",
        the corpus says "baptist", and _idf hands an UNSEEN token the highest rarity of all —
        df=0 is the rarest thing there is — so the absent plural won the subject seat and then
        partitioned out the entire keeping. An empty shelf reported by a full library.

        Only trailing-s/es variants, only when the token itself is absent, and only toward a form
        that exists: anything cleverer is a stemmer, and a stemmer quietly rewrites what the
        person asked.
        """
        if self._df(token) > 0 or len(token) < 4:
            return token
        candidates = [token + "s", token + "es"]
        if token.endswith("es"):
            candidates.append(token[:-2])
        if token.endswith("s"):
            candidates.append(token[:-1])
        for v in candidates:
            if len(v) >= 3 and self._df(v) > 0:
                return v
        return token

    def _with_variants(self, query_tokens: set) -> set:
        """Query tokens plus BOTH numbers of each, wherever that form exists in the index.

        The first version added a variant only when the asked form was ABSENT (df=0) — which left
        a hole measured live on 2026-08-02: "methodists" has df=31, so no "methodist" was added,
        `common = query ∩ doc` came up empty against the singular-only Methodist / Wesleyan voice
        card, and the card died at the no-common-tokens gate BEFORE the family partition could
        fire. The partition can only judge what scoring lets through, so the family has to enter
        at the tokens, not just at the verdict. Only forms the index actually contains are added —
        expansion never invents a word the corpus has never seen.
        """
        out = set(query_tokens)
        for t in query_tokens:
            out.add(self._present_form(t))
            for v in self.subject_family(t):
                if self._df(v) > 0:
                    out.add(v)
        return out

    @staticmethod
    def subject_family(subject: Optional[str]) -> set:
        """The subject in both numbers — "methodists" and "methodist" are one subject.

        The partition demanded the exact subject form, so the Methodist / Wesleyan voice card
        (which says "Methodist", singular) was partitioned OUT of a search for "methodists" —
        live, on a shelf that plainly holds the tradition. A card about the singular IS about the
        plural. Trailing s/es only; anything cleverer is a stemmer.
        """
        if not subject:
            return set()
        fam = {subject, subject + "s"}
        if subject.endswith("es") and len(subject) > 4:
            fam.add(subject[:-2])
        if subject.endswith("s") and len(subject) > 3:
            fam.add(subject[:-1])
        return fam

    def _subject_of(self, query_tokens: set, idf: Dict[str, float]) -> Optional[str]:
        """The rarest query word — what the question is ACTUALLY about.

        "Wesleyan Church" is about Wesleyans. "Church" is in half the library. And the seat must
        be held by a form the corpus CONTAINS: an absent token has df=0, which _idf reads as
        maximal rarity, so without the present-form step a typo or a plural would always win the
        seat and then partition out everything (the Southern Baptists failure).
        """
        if not query_tokens:
            return None
        chosen = max(query_tokens, key=lambda t: idf.get(t, 0.0))
        return self._present_form(chosen)

    def _score(self, card: dict, query_tokens: set, idf: Dict[str, float],
               subject: Optional[str] = None) -> float:
        """TF-IDF over the card text — with a HARD PARTITION on the subject word.

        Matt, 2026-08-01, on asking for the Wesleyan Church: *"It currently gives a bunch of not
        useful information... just random cards. Right now it's a dud."* He was right, and the
        cause was here.

        The score is sum(tf x idf) / log(len). TERM FREQUENCY OF A COMMON WORD OVERWHELMS THE
        PRESENCE OF A RARE ONE: a treatise that says "church" forty times outscores a card that
        says "Wesleyan" once. So "Wesleyan Church" returned Belgic Article 29 and Heidelberg Q85 —
        REFORMED confessions — to someone asking about a Wesleyan church. Not merely irrelevant:
        it hands a reader the tradition that disagrees with theirs, on the points they care about.
        And because the connection cloud then builds around the top hit, the whole neighbourhood
        came back Reformed. One bad first card poisons everything downstream.

        A WEIGHT WOULD NOT FIX THIS — any multiplier can be out-shouted by enough repetitions.
        This is a PARTITION: a card that does not contain the subject word cannot outrank one that
        does, however often it repeats the rest. The shape decides, not a tuned constant, so no
        amount of term frequency can reverse the flow. `SUBJECT_TIER` is larger than any reachable
        TF-IDF score by construction, which makes the two tiers non-overlapping.

        A one-word query is its own subject, so this changes nothing there.
        """
        doc_tokens = _tokens(_card_text(card))
        if not doc_tokens:
            return 0.0
        common = query_tokens & set(doc_tokens)
        if not common:
            return 0.0
        if max((idf.get(t, 0.0) for t in common), default=0.0) < self.min_idf:
            return 0.0
        counts = {t: 0 for t in common}
        for t in doc_tokens:
            if t in counts:
                counts[t] += 1
        # A frozen stub's text is its TITLE alone — scoring it by its real (tiny) length would
        # hand it an artificial length-normalization boost over full resident cards (caught by
        # the probe battery: gutenberg title stubs outscored the Bible-facts answerer). Score
        # stubs against a typical FULL card's document length instead, so freezing a shelf
        # never changes its cards' rank.
        doc_len = max(len(doc_tokens), 150) if card.get("frozen") else len(doc_tokens)
        score = sum(counts[t] * idf.get(t, 0.0) for t in common) / math.log(doc_len + 10)
        if len(common) == len(query_tokens):
            score *= 1.5
        # SUBSTANCE VS HEADWORD. Applied to the BASE score, before the tier addition below, so it
        # only ever reorders cards WITHIN whichever tier they already earned: a boosted stub still
        # cannot cross into the subject tier alone (base scores never approach SUBJECT_TIER's
        # scale — see its own comment), and among cards that already hold the subject, a real
        # answer now pulls ahead of a bare pointer that merely names it. A frozen card scored here
        # BEFORE rehydration still carries its true (stripped) stub body, so this correctly treats
        # it as a stub on that first pass; `search()` rehydrates and re-scores any frozen card that
        # clears zero, so the score actually used for ranking always reflects the real body.
        if len(str(card.get("body") or "")) >= STUB_BODY_CHARS:
            score *= SUBSTANCE_WEIGHT
        # THE PARTITION. Holding the subject word puts a card in the upper tier outright —
        # in EITHER number: a card that says "Methodist" is about "methodists" (the singular-only
        # voice card was partitioned out of a plural search, live, 2026-08-02). The seat is
        # chosen among the ASKED words, never among expansion variants — a rare junk variant
        # ("southerns") once stole the seat from "baptists". Search computes it once and passes
        # it in; never an instance attribute, because searches run concurrently across threads.
        if subject is None:
            subject = self._subject_of(query_tokens, idf)
        if subject and (self.subject_family(subject) & set(doc_tokens)):
            score += SUBJECT_TIER
        return float(score)

    def search(self, query: str, limit: int = 25, include_witness: bool = True,
               shelves: Optional[set] = None) -> List[dict]:
        """Ranked search over the keeping.

        The keeping is ONE SHARED library: by default BOTH surfaces draw the whole thing
        — the .com includes the religious cards too (Matt, 2026-06-26: "the religious
        cards can be included"; "we are not hiding anything"). `include_witness=False`
        gives an optional scrubbed view if a caller ever wants secular-only results.

        `shelves` (a set) restricts the search to those shelves — the DECK fast-path (the Hare):
        scoring only the deck's cards instead of the whole keeping. None = the whole library
        (the Tortoise). A deck search that comes up short can always fall back to the full one."""
        # A truthy non-string query (e.g. an int from an uncoerced MCP tool call — args.get("query")
        # with no str() at the call site) would otherwise crash here: "query or ''" only substitutes
        # the fallback for a FALSY query, so a non-empty int/list survives and .lower() raises
        # AttributeError deep inside _tokens(). This is the one shared search entry point (the HTTP
        # /search route and /ask already coerce before calling in, but the MCP search tool does not)
        # — coerce once, here, so every caller is safe regardless of what reaches this function.
        query = str(query) if query else ""
        # STOPWORDS ARE NOT A SUBJECT — the same rule as the shard matcher, from the same list, so
        # the two doors can never drift apart.
        #
        # IDF alone does NOT solve this, which is why the bug survived here after the shard side was
        # fixed. `_idf` is log(n / (df + 1)): a word in 20k of 478k cards still scores ~3.2, small
        # next to a rare term but very far from zero. So when the DISTINCTIVE word matches nothing
        # — "what is Mahavira", and we hold no Mahavira — the only tokens left contributing are
        # "what" and "is", cards containing them score above zero, and the reader is handed Marcus
        # Aurelius as though it were an answer. Measured live 2026-08-01 on the 1,000-probe assay.
        #
        # A gap must be allowed to report itself; a miss is what feeds the want list. Dropping the
        # stopwords before candidates or scoring means nothing can be retrieved on their strength
        # alone. A query made only of stopwords asks about nothing and returns nothing.
        from .corpus_db import _STOP          # one list, both matchers (corpus_db imports nothing here)
        asked = {t for t in _tokens(query) if t not in _STOP}
        # THE PRESENT FORM RIDES ALONG — for scoring. The SUBJECT SEAT is chosen among the words
        # actually ASKED: expansion once added "southerns" (a rare variant of a common word,
        # df tiny so idf huge) and the junk variant stole the seat from "baptists". Variants
        # widen what can match; they never redefine what the question is about.
        query_tokens = self._with_variants(asked)
        # the seat belongs to the words actually asked — computed once, passed to scoring;
        # never instance state (searches run concurrently across handler threads)
        seat = self._subject_of(asked, self._idf(asked)) if asked else None
        if not query_tokens:
            return []
        idf = self._idf(query_tokens)
        # exact-match targets: the query as typed, and its canonical verse forms — so a verse
        # lookup ("Philippians 4:13", the most common human search) ranks the verse card first
        # instead of a fuzzy book match. Reuses the growth engine's one verse canonicalizer.
        from . import growth as _growth
        qn = " ".join((query or "").lower().split())
        q_exact = {qn} | {r.lower() for r in _growth.refs_in_text(query or "")}
        scored = []
        for cid in self._candidates(
                query_tokens, seat_family=(self.subject_family(seat) if seat else None)):
            c = self.cards.get(cid)
            if not c or not is_public(c):
                continue
            if not include_witness and c.get("surface") == "witness":
                continue
            if shelves is not None and c.get("shelf") not in shelves:
                continue
            s = self._score(c, query_tokens, idf, subject=seat)
            if s > 0 and c.get("frozen"):
                # rank-neutral freezing: a stub that matched on TITLE is re-scored on its real
                # text from the shard, so freezing a shelf never reorders results. Only stubs
                # passing the distinctiveness floor pay the point lookup (a handful per query).
                full = rehydrate(c)
                if full is not c:
                    c = full
                    s = self._score(c, query_tokens, idf, subject=seat)
            if s > 0:
                title_n = " ".join(str(c.get("title", "")).lower().split())
                ref_n = " ".join(str((c.get("source") or {}).get("ref", "")).lower().split())
                if title_n in q_exact or (ref_n and ref_n in q_exact and title_n in q_exact):
                    s *= 9.0                              # THE card for this exact reference/title
                elif q_exact and (title_n in q_exact or ref_n in q_exact):
                    s *= 4.0
                # a practical/how-to question prefers the practical field library over an
                # incidentally-titled book or species (so "build a fire" gets the how-to, not fire ants)
                if c.get("shelf") == "survival" and (_PRACTICAL & query_tokens):
                    s *= 3.0
                # A THEORY IS LOAD-BEARING (Matt, 2026-08-02: "Theories should be weighted heavier
                # than a standard card."). The theories shelf is 99 cards out of 550,000, each one
                # a thing the sciences actually run on, each now carrying its own place in the
                # assembled floor — what it rests on, what limits it, what shares its form. When a
                # reader's question touches one, the theory is the card that orients everything
                # else, so it outranks an incidental mention in a book that happens to use the
                # same word. Applied INSIDE the s > 0 branch, so it can only lift a card the
                # partition already admitted — a boost can never smuggle in an off-subject hit.
                elif c.get("shelf") == "theories":
                    s *= THEORY_WEIGHT
                scored.append((s, c))
        # a TOTAL order: equal scores tie-break on id, so the ranking is a function of the
        # cards and the query alone — never of construction order (invariant I)
        scored.sort(key=lambda x: (-x[0], str(x[1].get("id") or "")))

        # NEVER PAD THE TAIL WITH CARDS THAT MISS THE SUBJECT. The partition put subject-holders
        # in the upper tier, but ranking alone still let the leftovers fill the limit: live,
        # "Wesleyan Church" came back with six Wesleyan cards and then a Kensington church
        # directory and "Doctrines Objected to in the Church of Rome" at 7 and 8, purely to reach
        # eight. Padding a count with things a reader must discard is the same lie as a silent cap
        # — it reads as "here is what we hold" when two of them are noise.
        #
        # So when ANY card holds the subject word, only those are served. Six true results beat
        # eight with two lies, and the count then means what it says. (The shard merge already
        # excludes rather than demotes; this makes both halves of the rule behave alike, which
        # they did not, and that inconsistency is what reached the reader.)
        if scored and scored[0][0] >= SUBJECT_TIER:
            scored = [(s, c) for s, c in scored if s >= SUBJECT_TIER]
        return [c for _s, c in scored[:max(1, int(limit))]]


