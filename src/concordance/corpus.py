def load_cards(path: Optional[Path] = None,
               _df_out: Optional[Dict[str, int]] = None,
               _frozen_out: Optional[Dict[str, tuple]] = None,
               _skip_frozen_in: Optional[set] = None,
               _contrib_out: Optional[Dict[str, List[int]]] = None,
               _offsets_in: Optional[Dict[str, List[int]]] = None,
               _offsets_out: Optional[Dict[str, List[int]]] = None,
               _nofile_out: Optional[Dict[str, Any]] = None,
               _bridges_out: Optional[Dict[str, List[dict]]] = None) -> Dict[str, dict]:
    """Load cards from a JSONL file into an id -> card dict. Empty if absent.

    `_df_out` (internal — default_corpus passes it): a dict that receives the document
    frequency of each frozen card's full-text tokens, streamed during the load so no per-card
    token list ever materializes. Corpus takes it as `df_extra`, keeping the corpus-wide IDF
    statistics identical whether a shelf is frozen or resident.

    `_frozen_out` (internal — LAZY STUBS, increment 2): a dict that receives, for each PUBLIC
    frozen card, a COMPACT entry `id -> (call, title)` instead of a resident stub dict. The full
    card (body, connections, facets, provenance) is served from the shard on demand (get_card /
    rehydrate). This is what makes resident RAM scale with the CORE shelf, not the whole keeping
    (measured 2026-09-26: the stub dicts were ~96% of resident memory). Withheld frozen cards are
    dropped entirely (never browsable/served), but still stream their DF so IDF is unchanged.

    `_bridges_out` (internal — default_corpus passes it): a dict that receives, per FROZEN card id, the
    bridge edges whose endpoint is that card (id -> [edges]). A bridge overlay is resolved against the FULL
    keeping — the resident cards AND the frozen index — so a row to a frozen-shelf card (the Gutenberg
    catalogue) applies: the resident side carries its edge inline, the frozen side rides here and
    Corpus.full merges it on read. Without it a frozen endpoint is not reachable in this load, and such a
    row counts as unresolved (warned, tallied in LOAD_PHASES) rather than half-applied."""
    p = path or _cards_path()
    out: Dict[str, dict] = {}
    if not p.exists():
        return out
    frozen = frozen_shelves()
    from time import perf_counter as _pc
    _ph: Dict[str, Any] = {"frozen_df_ms": 0.0, "frozen_cards": 0, "resident_cards": 0,
                           "frozen_cards_cached": 0, "files_skipped": 0, "files_seeked": 0,
                           "dup_edges_dropped": 0,
                           # the bridge overlays, tallied (never silent): rows read; applied on both cards;
                           # left UNRESOLVED because an endpoint is in neither the resident keeping nor the
                           # frozen index; and edges that went to the frozen side table (_bridges_out)
                           "bridge_rows": 0, "bridge_rows_applied": 0, "bridge_rows_unresolved": 0,
                           "bridge_edges_frozen_side": 0, "bridge_unresolved_by_overlay": {}}
    from sys import intern as _intern   # one object per distinct call number / surface across 840k frozen entries
    # THE FROZEN CACHE (2026-10-08, frozen_cache.py): `_contrib_out` receives, per SOURCE FILE NAME, how many
    # [frozen, resident] cards it held (so default_corpus can key the cache on exactly the files that matter,
    # and skip wholesale the ones with nothing resident); a file named in `_skip_frozen_in` has its frozen
    # cards' DF and index entries already loaded from the cache (a safety net: on a hit those files are read by
    # `_offsets_in` — only their RESIDENT lines, by byte offset — so no frozen card is even seen; a file whose
    # recorded offsets are empty is not opened at all). Everything else is handled live, exactly as before.
    _cur: Dict[str, Optional[str]] = {"name": p.name}

    def _keep(c: dict) -> None:
        # SHELVE at the gate: every card gets its call + facets here, computed from the FULL card
        # (bands present) before any frozen handling — so a newly-carded shelf is walkable and
        # facet-reachable the instant it loads, with no separate classify pass.
        shelve(c)
        # A frozen-shelf card is NOT held resident (increment 2): its full text streams to _df_extra
        # (IDF unchanged), a PUBLIC card leaves only a compact (call, title) index entry for browse /
        # the call-tree, and the full card rehydrates from the shard on read. Withheld frozen: DF only.
        if c.get("shelf") in frozen:
            _ph["frozen_cards"] += 1
            src = _cur["name"]
            if _contrib_out is not None and src is not None:
                _contrib_out.setdefault(src, [0, 0])[0] += 1
            if _skip_frozen_in and src is not None and src in _skip_frozen_in:
                _ph["frozen_cards_cached"] += 1
                return                   # its DF and index entry came from the frozen cache
            if _df_out is not None:
                _t = _pc()
                toks = set(_tokens(_card_text(c)))
                for t in toks:
                    _df_out[t] = _df_out.get(t, 0) + 1
                if src is None and _nofile_out is not None:
                    # a frozen card from a NON-file source (the prophecy signposts, shaped at load): counted
                    # here, but kept OUT of the saved cache — a hit tokenizes it live, so it must not be in both
                    nd = _nofile_out["df"]
                    for t in toks:
                        nd[t] = nd.get(t, 0) + 1
                _ph["frozen_df_ms"] += (_pc() - _t) * 1000.0
            if _frozen_out is not None and is_public(c):
                _frozen_out[c["id"]] = (_intern(c.get("call") or ""), c.get("title") or c["id"],
                                        _intern(c.get("surface") or "?"))
                if src is None and _nofile_out is not None:
                    _nofile_out["ids"].append(c["id"])
            return False                 # no resident stub — the shard holds the body + the graph
        _ph["resident_cards"] += 1
        if _contrib_out is not None and _cur["name"] is not None:
            _contrib_out.setdefault(_cur["name"], [0, 0])[1] += 1
        # exact duplicate inline edges (same target + same relationship) are dropped at the gate, first
        # occurrence kept (issue #25) — so the resident graph never carries the same edge twice.
        _ph["dup_edges_dropped"] += _dedupe_connections(c)
        out[c["id"]] = c
        return True

    def _line(raw: bytes, off: Optional[int]) -> None:
        line = raw.strip()
        if not line:
            return
        try:
            c = json.loads(line)
        except (json.JSONDecodeError, UnicodeDecodeError):
            return
        if isinstance(c, dict) and c.get("id"):
            if _keep(c) and off is not None and _offsets_out is not None and _cur["name"] is not None:
                _offsets_out.setdefault(_cur["name"], []).append(off)

    def _read(fp: Path, name: Optional[str]) -> None:
        """One source file. Cold path: every line, recording the byte offset of each line that stayed
        resident. Cache hit (the file is in `_offsets_in`, byte-identical under the key): seek to exactly
        those lines and read nothing else - a file with none is never opened. THE BOOT CUT (2026-10-08 v3):
        a hit used to parse and shelve ~480k frozen cards from mixed files only to discard them."""
        _cur["name"] = name
        offs = _offsets_in.get(name) if (_offsets_in is not None and name is not None) else None
        if offs is not None and not offs:
            _ph["files_skipped"] += 1      # cached, and nothing resident in it: not even opened
            return
        with open(fp, "rb") as f:
            if offs is not None:
                _ph["files_seeked"] += 1
                for off in offs:
                    f.seek(off)
                    _line(f.readline(), None)
            else:
                off = 0
                for raw in f:
                    _line(raw, off)
                    off += len(raw)

    _t_main = _pc()
    _read(p, p.name)
    _ph["cards_jsonl_ms"] = round((_pc() - _t_main) * 1000.0, 1)
    _t_extras = _pc()
    # further sources that join the SAME graph as Scripture and the tradition:
    #   verified_cards.jsonl — minted live from sealed verifications (data-only, gitignored)
    #   reference_cards.jsonl — the deep reference work already in the verifiers (periodic table,
    #                           physical constants, …), carded and GIT-TRACKED so the content is
    #                           on github, not only in the code
    if path is None:
        #   works_cards.jsonl — The Works: every worked, engine-sealed demonstration carded as a
        #                       seed in the keeping (minted by compendium.build_all, data-only)
        for extra in EXTRA_CARD_SOURCES:
            xp = p.parent / extra
            if not xp.exists():
                continue
            _read(xp, extra)
        # THE SIGNPOSTS AS CARDS (2026-10-02; Matt: "the nations at the tower of Babel having parts of
        # the story, but Christ fulfilled them"). data/prophecy/signposts.jsonl served /prophecy alone —
        # search and ask could not reach the clearest statements of the hole Christ filled (measured:
        # search("the way logos derek") -> nothing; /card?id=signpost_... -> not found). ONE source: the
        # same file, shaped as cards at load time — never a second file to drift. Shelf `signposts`,
        # a member of the foreshadows spine, so the walk from any nation's part leads to the Way.
        from . import prophecy as _prophecy       # the same resolver /prophecy uses (honors its env)
        sp_path = _prophecy._file()
        if not sp_path.exists():
            sp_path = p.parent / "prophecy" / "signposts.jsonl"
        _cur["name"] = None              # signposts are shaped at load, not a cacheable source file: always live
        if sp_path.exists():
            with open(sp_path, encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        rec = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    c = _signpost_card(rec)
                    if c is not None and c["id"] not in out:
                        _keep(c)
        # THE BRIDGES RESOLVE AGAINST THE FULL KEEPING (2026-10-31). Every source file above has been read by
        # now, so file order was never the gap — but a FROZEN-shelf card never enters `out` (lazy stubs: only its
        # (call, title) index entry), so a row to one (seed_computer_science: card_cs_logic_gates -> a Gutenberg
        # catalogue card, seen live 2026-10-31) was dropped here by a silent `continue` while its sibling row to a
        # resident theory card applied. An endpoint now counts as present when it is resident OR in the frozen
        # index; the frozen side's edge goes to `_bridges_out` and Corpus.full merges it on read. Rows that still
        # do not resolve are counted per overlay, warned with examples, and reported in LOAD_PHASES.
        for overlay in BRIDGE_OVERLAYS:
            st = _apply_bridges(out, p.parent / overlay, frozen=_frozen_out, frozen_edges=_bridges_out)
            _ph["bridge_rows"] += st["rows"]
            _ph["bridge_rows_applied"] += st["applied"]
            _ph["bridge_rows_unresolved"] += st["unresolved"]
            _ph["bridge_edges_frozen_side"] += st["frozen_side"]
            if st["unresolved"]:
                _ph["bridge_unresolved_by_overlay"][overlay] = st["unresolved"]
        if _ph["bridge_rows_unresolved"]:
            _log.warning("bridges: %d of %d row(s) still unresolved at the end of the load, by overlay %s — "
                         "no edge attached for them on either card (0-FP); each overlay's warning names examples",
                         _ph["bridge_rows_unresolved"], _ph["bridge_rows"], _ph["bridge_unresolved_by_overlay"])
    _ph["extras_ms"] = round((_pc() - _t_extras) * 1000.0, 1)
    _ph["frozen_df_ms"] = round(_ph["frozen_df_ms"], 1)
    LOAD_PHASES.update(_ph)
    return out


