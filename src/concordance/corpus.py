# A query token must be at least this distinctive (high IDF) to count as a real hit.
# Tuned for a large corpus; lower it for small fixtures.
MIN_DISTINCTIVE_IDF = 1.5

_FIELDS = ("title", "body", "bands", "source")

# How-to INTENT markers (verbs only — no nouns like "fire"/"water", so this never hijacks a topic
# search). Used only to lift the practical field library when a question is clearly practical; and
# safe by construction — the boost multiplies a survival card only if it ALREADY matched the query.
_PRACTICAL = frozenset({
    "how", "build", "make", "start", "light", "purify", "treat", "cure", "stop", "find", "tie",
    "preserve", "store", "grow", "plant", "raise", "signal", "navigate", "cook", "fix", "repair",
    "survive", "forage", "trap", "prepare", "canning", "dry", "sharpen", "filter", "splint",
})


def _tokens(text: str) -> List[str]:
    return re.findall(r"[a-zA-Z][a-zA-Z']{1,}", (text or "").lower())


def _card_text(card: dict) -> str:
    src = card.get("source") or {}
    return " ".join([
        card.get("title", ""),
        (card.get("body", "") or "")[:1000],
        " ".join(card.get("bands") or []),
        src.get("ref", ""),
        src.get("label", ""),
    ]).lower()


PUBLIC_STAGES = frozenset({"public", "featured"})

# Disallowed-to-REDISTRIBUTE license markers. Two classes are a legal issue to serve publicly:
# share-alike (CC-BY-SA — its viral copyleft could pull the WHOLE corpus under SA) and
# non-commercial (CC-BY-NC* — forbids the free-to-all use that is the point). PD / CC0 / CC-BY
# (attribution-only) are fine, credited by each card's own source label. Mirror of the mint-side
# guard in tools/card_sources.py (_DISALLOWED_LICENSE) — the two boundaries stay in step.
_DISALLOWED_LICENSE = ("cc-by-sa", "cc by-sa", "share-alike", "sharealike",
                       "cc-by-nc", "cc by-nc", "non-commercial", "noncommercial")
# Legacy sources that ARE disallowed-license but whose cards were minted before the guard and carry
# only the SOURCE NAME in their label, never the license string. OEIS (CC-BY-NC-SA) is the live
# case — 6,000 cards served under a bare "OEIS — …" label, slipping the marker scan (found 2026-08-08
# in the pre-launch shelf audit). Matched by source name (label + url) so the name alone withholds.
_DISALLOWED_SOURCE = ("oeis", "phoible", "drugcentral")

# Back-compat alias: the flag on a frozen-shelf stub and older callers is still named `share_alike`.
_SHARE_ALIKE = _DISALLOWED_LICENSE


def _is_share_alike(card: dict) -> bool:
    """True iff a card declares a license we may not publicly REDISTRIBUTE — share-alike (CC-BY-SA)
    or non-commercial (CC-BY-NC*) — OR names a known such source. Read from the free-text source
    label, `source.url`, and any `extra.license` (a structured `license` field would be more robust;
    tracked as a follow-up). HYG + PHOIBLE match by their CC-BY-SA label; OEIS matches by source name.

    A FROZEN-SHELF STUB drops `source`/`extra` to save memory, so it carries a precomputed
    `share_alike` bool (set at stub-build time while the label was still present) — honoured here
    first, so is_public() judges a stub exactly as it judges the full card. Without this, search
    (which runs over stubs) leaked CC-BY-SA cards that card_get correctly withheld (found live)."""
    flag = card.get("share_alike")
    if flag is not None:
        return bool(flag)
    src = card.get("source")
    label = (src.get("label") if isinstance(src, dict) else "") or ""
    url = (src.get("url") if isinstance(src, dict) else "") or ""
    extra = card.get("extra")
    lic = (extra.get("license") if isinstance(extra, dict) else "") or ""
    if any(m in (str(label) + " " + str(lic)).lower() for m in _DISALLOWED_LICENSE):
        return True
    # a known disallowed source recognised by name, for legacy cards whose label lacks the license
    return any(s in (str(label) + " " + str(url)).lower() for s in _DISALLOWED_SOURCE)

# Larger than any reachable TF-IDF score, so cards holding the query's rarest word form a
# strictly higher tier than those that do not. A partition, not a weight: no amount of
# repeating a common word can cross it.
SUBJECT_TIER = 1000.0

# A theory card outranks an incidental mention of the same words. Deliberately a WEIGHT and not a
# tier: the subject partition still decides who is in the running, and this only orders those who
# already are. Set at 4.0 — above the survival field library's 3.0 (a how-to should still win a
# how-to question) and well under the exact-title 9.0, so naming a card by its title still wins.
THEORY_WEIGHT = 4.0

# THE RANKER WAS BLIND TO SUBSTANCE VS HEADWORD (docs/SOP/subsystems/keeping.md's own "Refine" —
# the highest-leverage open item, 2026-09-02). ~67% of the keeping are stubs (a pronunciation
# guide, a bare title+link — ops.STUB_BODY_CHARS defines the line), and the subject partition
# above is lexical presence only: it can tell "about this" from "not about this," never a thin
# gloss from a real excerpt that answers the question. A weight, not a tier, like THEORY_WEIGHT —
# it only ever reorders cards the partition already admitted. Set modestly (well under
# THEORY_WEIGHT) because it distinguishes within EVERY tier a query reaches, not one narrow shelf.
SUBSTANCE_WEIGHT = 2.0


def is_public(card: dict) -> bool:
    """True iff a card may appear on ANY public read path — an ALLOWLIST, not a denylist.
    ONE source of truth (graph.py imports this too, so the two can never diverge): every
    stage except public/featured — private, public_review, archived, quarantine, retracted —
    is withheld. A denylist here (archived/quarantine only) is exactly what leaked the
    operator's private cards onto the public surface. On top of the stage allowlist, two
    withholding guards (more restrictive, never less): share-alike-licensed cards (CC-BY-SA —
    a legal issue to redistribute) and generated cards (the conduit contract) never go public."""
    if not isinstance(card, dict) or card.get("retracted"):
        return False
    if (card.get("lifecycle_stage") or "public") not in PUBLIC_STAGES:
        return False
    # LICENSE (red team 2026-08-06, Matt's call "drop what could get us in trouble"): never publicly
    # REDISTRIBUTE share-alike content — its copyleft could pull the whole corpus under SA. Withheld
    # here, not deleted (the bodies stay archived on the drive). A PD stub card ABOUT each such source
    # still serves, so the shelf is not a silent hole. See _is_share_alike.
    if _is_share_alike(card):
        return False
    # The conduit contract at the serving boundary: a generated card is never served publicly.
    if card.get("generated") is True:
        return False
    return True


