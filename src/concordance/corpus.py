def _cards_path() -> Path:
    env = os.environ.get("CONCORDANCE_CARDS_JSONL", "").strip()
    if env:
        return Path(env)
    data = os.environ.get("CONCORDANCE_DATA_DIR", "").strip()
    return (Path(data) if data else Path("data")) / "cards.jsonl"


def load_cards(path: Optional[Path] = None,
               _df_out: Optional[Dict[str, int]] = None) -> Dict[str, dict]:
    """Load cards from a JSONL file into an id -> card dict. Empty if absent.

    `_df_out` (internal — default_corpus passes it): a dict that receives the document
    frequency of each frozen card's full-text-only tokens, streamed during the load so no
    per-card token list ever materializes. Corpus takes it as `df_extra`, keeping the
    corpus-wide IDF statistics identical whether a shelf is frozen or resident (the probe
    battery caught title-only indexing re-ranking two RESIDENT cards on an unrelated query)."""
    p = path or _cards_path()
    out: Dict[str, dict] = {}
    if not p.exists():
        return out
    frozen = frozen_shelves()

    def _keep(c: dict) -> None:
        # a frozen-shelf card loads as a stub — the graph resident, the weight on the shard
        if c.get("shelf") in frozen:
            full_toks = set(_tokens(_card_text(c)))
            c = {k: v for k, v in c.items() if k in _STUB_KEEPS}
            c["frozen"] = True
            if _df_out is not None:
                for t in full_toks - set(_tokens(_card_text(c))):
                    _df_out[t] = _df_out.get(t, 0) + 1
        out[c["id"]] = c

    with open(p, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                c = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(c, dict) and c.get("id"):
                _keep(c)
    # further sources that join the SAME graph as Scripture and the tradition:
    #   verified_cards.jsonl — minted live from sealed verifications (data-only, gitignored)
    #   reference_cards.jsonl — the deep reference work already in the verifiers (periodic table,
    #                           physical constants, …), carded and GIT-TRACKED so the content is
    #                           on github, not only in the code
    if path is None:
        #   works_cards.jsonl — The Works: every worked, engine-sealed demonstration carded as a
        #                       seed in the keeping (minted by compendium.build_all, data-only)
        for extra in ("receipt_cards.jsonl",     # every minted seal, carded — see cas._mint_receipt_card
                      "acquired_cards.jsonl",    # cards a person CHOSE from the want list's options
                                                 # (tools/shepherd_rounds.py --choose; source-to-source)
                      "verified_cards.jsonl", "reference_cards.jsonl", "keystone_seeds.jsonl",
                      "nesting_seeds.jsonl", "ncs_seeds.jsonl", "works_cards.jsonl", "theory_cards.jsonl",
                      "fieldkit_cards.jsonl", "playbook_cards.jsonl", "systems_cards.jsonl",
                      "access_tools_cards.jsonl",   # the connection to lawful free tools (logistics: tag onto paid carriers)
                      "church_cards.jsonl",         # the churches, calibrated from their own confessions (not judged)
                      "contributors_cards.jsonl",   # the builders of the Floor (historians/scientists/mathematicians), credited with love
                      "religions_cards.jsonl",      # the pre-Christian faiths as foreshadow (Acts 17) + the test of the spirits (1 John 4)
                      "survival_cards.jsonl",       # the field library — outdoor/survival/bushcraft/homestead, PD sources (serve the off-grid + destitute)
                      # The plumb-line: the whole Bible in the original tongues (Greek NT + Hebrew OT),
                      # one card per verse. Academics first. Spines root in the Word.
                      "scripture_spines.jsonl", "scripture_cards.jsonl",
                      # The OEIS core — the foundational integer sequences (academics: mathematics).
                      "oeis_spine.jsonl", "oeis_cards.jsonl",
                      # The tree of life — the recognizable organisms (academics: biology).
                      "taxonomy_spine.jsonl", "taxonomy_cards.jsonl",
                      # The languages of the earth — PHOIBLE/Glottolog (academics: linguistics).
                      "language_spine.jsonl", "language_cards.jsonl",
                      # More stored sources — RFCs (internet standards), Matthew Henry commentary,
                      # Spurgeon sermons, and the Compendium of Physical Activities (METs).
                      "reference_extra_spines.jsonl", "reference_extra_cards.jsonl",
                      # Acquired: the Great Books — Project Gutenberg (~77k stub cards -> the full text).
                      "gutenberg_spine.jsonl", "gutenberg_cards.jsonl",
                      # Acquired: history — dated events from Wikidata (CC0), stub -> the full record.
                      "history_spine.jsonl", "history_cards.jsonl",
                      # The study tables (Harmony of the Gospels + the OT/NT/Church-History
                      # Timeline) carded, so the events are IN the keeping — findable by /search,
                      # walkable in the graph/brain, routable by wayfinding — and not marooned
                      # behind their own two routes. Minted by tools/card_study_tables.py.
                      "study_spines.jsonl", "study_cards.jsonl",
                      # The Biblical Encyclopedia as Cards — Easton's 3,962 entries, stub+link
                      # into /characters, boxed by category (the card-catalog drawers). Minted by
                      # tools/card_encyclopedia.py.
                      "encyclopedia_cards.jsonl",
                      # The domain reference cores (GAPS G1/G2): a spine per domain the engine
                      # can actually check, plus one WORKED-CHECK card per claim — the inputs,
                      # the engine's verdict, and the falsehood it refuses. Substance minted from
                      # runs that happened; nothing minted for an unproven domain.
                      "domain_core_cards.jsonl",
                      # The commentaries carded VERSE BY VERSE (44,371 cards, avg 1,462 chars of
                      # the commentator's own PD words, 99% linked to their verse by a found
                      # edge). Rides the `commentary` shelf -> the `word` shard, so the bodies
                      # are frozen freight and the resident cost is a stub.
                      "commentary_verse_cards.jsonl",
                      # The practical stores carded (seeding loop, practical pass 1): the
                      # apothecary monographs, the verified almanac, the coach curriculum —
                      # substance we already held that had no card at all.
                      "practical_cards.jsonl",
                      # Nave topical index SCANNED into topics + speaks_to edges (structure
                      # taken, the work's own text left with the work).
                      "topical_cards.jsonl",
                      # THE RECURRING ARCHITECTURE (tools/card_doctrine.py) — concepts gathered
                      # from Matt's six planning documents, which describe one pattern in six
                      # materials. Carried as concepts, never adopted as policy: each card names
                      # its document and says where the idea already bears weight here.
                      "doctrine_cards.jsonl",
                      # ISBE 1915 (D5) — 9,380 scholarly stub cards; the full public-domain
                      # article renders from data/acquisitions/isbe.db on the card page.
                      "isbe_cards.jsonl",
                      # The Corpus — technical, academic cards minted from the stored sources
                      # (nuclides, stars, foods, ports, indicators, …); always growing.
                      "source_spines.jsonl", "source_cards.jsonl", "web_cache.jsonl",
                      # The harvested map — inline SEMANTIC edges minted as sealed connection cards
                      # (cites, proof-texts, sections, families, grafts) so the constellation reflects
                      # the whole keeping. The member_of skeleton stays the floor tree's (tools/mint_edges.py).
                      "minted_edges.jsonl"):
            xp = p.parent / extra
            if not xp.exists():
                continue
            with open(xp, encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        c = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    if isinstance(c, dict) and c.get("id"):
                        _keep(c)
        for overlay in ("reference_bridges.jsonl", "keystone_bridges.jsonl",
                        "nesting_bridges.jsonl", "works_bridges.jsonl", "element_bridges.jsonl",
                        "ncs_bridges.jsonl"):
            _apply_bridges(out, p.parent / overlay)
    return out


# inverse labels for DIRECTIONAL (hierarchical) edges, so the reciprocal points the other way and
# the floor can be walked as a tree. Anything not here is treated as symmetric (lateral) — the
# reciprocal keeps the same label (shares_scripture, same_family, names_the_created_thing, …).
_INVERSE_REL = {
    "member_of": "has_member", "part_of": "has_part", "nested_in": "contains",
    "figure_of": "has_figure", "pre_registered_validation_of": "validated_by",
    "leads_to": "reached_from", "points_beyond_itself": "pointed_to_by",
}


def _apply_bridges(cards: Dict[str, dict], overlay: Path) -> None:
    """Graft the two trees: apply the git-tracked reference→Scripture bridges reciprocally onto
    both cards' connection lists at load time. The 25k cards.jsonl is never mutated on disk — the
    edges live in their own small overlay so they survive any regeneration of the reference cards.
    0-FP: each bridge is an exact-subject match (an element or crop the Bible also names)."""
    if not overlay.exists():
        return
    for line in overlay.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            e = json.loads(line)
        except json.JSONDecodeError:
            continue
        a, b = e.get("a"), e.get("b")
        rel = e.get("relationship") or "names_the_created_thing"
        ev = e.get("evidence") or ""
        ca, cb = cards.get(a), cards.get(b)
        if not ca or not cb:
            continue
        # hierarchical edges are DIRECTIONAL — the reciprocal carries the inverse label so the floor
        # can be walked as a tree (up = member_of/part_of/…, down = has_member/has_part/…). Lateral
        # edges (shares_scripture, same_family, names_the_created_thing) stay symmetric.
        rev = _INVERSE_REL.get(rel, rel)
        for src, dst, r in ((ca, b, rel), (cb, a, rev)):
            links = src.setdefault("connections", [])
            if not any(isinstance(x, dict) and x.get("to_card_id") == dst for x in links):
                links.append({"to_card_id": dst, "relationship": r, "evidence": ev})


def add_to_default(card: dict) -> None:
    """Add one card to the live default corpus if it is already built (best-effort)."""
    if _DEFAULT is not None:
        _DEFAULT.add_card(card)


def default_corpus(path: Optional[Path] = None) -> Corpus:
    global _DEFAULT
    if _DEFAULT is None:  # double-checked lock: build once, even under concurrent first-hits
        with _DEFAULT_LOCK:
            if _DEFAULT is None:
                df: Dict[str, int] = {}
                _DEFAULT = Corpus(load_cards(path, _df_out=df), df_extra=df)
    return _DEFAULT


def search(query: str, limit: int = 25, include_witness: bool = True,
           shelves: Optional[set] = None) -> List[dict]:
    """Ranked search over the default corpus (cards.jsonl) — the floor's retrieval primitive.
    The keeping is shared across both surfaces by default (the .com includes the religious
    cards too); pass include_witness=False for an optional secular-only view. `shelves` scopes
    the search to a deck (the Hare fast-path).

    When shelves are FROZEN (riding the shards), their resident stubs only match on title —
    so the shard FTS (which indexes the full text) fills the remaining slots, and any stub
    that made the cut is rehydrated. The reader never sees a lighter answer because the
    shelf rode the shard."""
    out = default_corpus().search(query, limit, include_witness, shelves)
    frozen = frozen_shelves()
    if frozen and (shelves is None or (set(shelves) & frozen)) and len(out) < limit:
        from . import corpus_db
        corpus_db.thaw_for(*frozen)
        have = {c.get("id") for c in out}
        for hit in corpus_db.search(query, limit=limit, include_witness=include_witness):
            if (hit.get("shelf") not in frozen or hit.get("id") in have
                    or (shelves is not None and hit.get("shelf") not in shelves)
                    or not is_public(hit)):
                continue        # resident shelves are already fully scored — merge only frozen freight
            out.append(hit)
            have.add(hit.get("id"))
            if len(out) >= limit:
                break
    return [rehydrate(c) for c in out]


# ── Library primitives (ported from 1.0's card tools, over the same corpus) ──────────────

def _brief(c: dict) -> Dict[str, Any]:
    return {"id": c.get("id"), "title": c.get("title"), "shelf": c.get("shelf"),
            "surface": c.get("surface"), "snippet": (c.get("body", "") or "")[:200]}


def get_card(card_id: str) -> Optional[dict]:
    """Fetch one PUBLIC card (the full record) by id, or None. Non-public cards
    (private / public_review / archived / quarantine / retracted) are never returned —
    this is the boundary render_card_html and /card rely on."""
    c = default_corpus().cards.get((card_id or "").strip())
    return rehydrate(c) if (c is not None and is_public(c)) else None


def browse(shelf: Optional[str] = None, limit: int = 20, offset: int = 0) -> Dict[str, Any]:
    """Paginated browse over the keeping, optionally filtered to a shelf. Returns briefs."""
    cards = [c for c in default_corpus().cards.values() if is_public(c)]
    if shelf:
        cards = [c for c in cards if (c.get("shelf") or "").lower() == shelf.lower()]
    cards.sort(key=lambda c: ((c.get("shelf") or ""), (c.get("title") or c.get("id") or "")))
    total = len(cards)
    offset = max(0, offset)
    limit = max(1, min(limit, 100))
    return {"total": total, "offset": offset, "limit": limit,
            "shelf": shelf, "cards": [_brief(rehydrate(c)) for c in cards[offset:offset + limit]]}


def stats() -> Dict[str, Any]:
    """Counts over the keeping — total, by shelf, by surface."""
    from collections import Counter
    cards = [c for c in default_corpus().cards.values() if is_public(c)]
    out = {"total": len(cards),
           # EVERY shelf, not the largest 40. This was `most_common(40)`, and the library's browse
           # dropdown is built from it — so 63 of 103 shelves could not be reached by browsing at
           # all, while /cards?shelf=X served them perfectly well. A cap that hides two-thirds of
           # the keeping from the one control meant for reaching it is a silent truncation, and it
           # reads to a visitor as "this is all there is".
           "by_shelf": dict(Counter((c.get("shelf") or "?") for c in cards).most_common()),
           "by_surface": dict(Counter((c.get("surface") or "?") for c in cards))}
    fz = frozen_shelves()
    if fz:
        # named, never silent: these shelves are resident as stubs (graph + titles), full
        # bodies riding the SQLite shards and rehydrated on read
        out["frozen_shelves"] = sorted(fz)
    return out


def daily(seed: Optional[str] = None) -> Optional[dict]:
    """A deterministic 'card of the day' — same card all day, different each day. Stable: the
    seed (default today's UTC date) hashes to an index, so it needs no stored state."""
    import hashlib
    import time as _time
    ids = sorted(cid for cid, c in default_corpus().cards.items() if is_public(c))
    if not ids:
        return None
    if seed is None:
        seed = _time.strftime("%Y-%m-%d", _time.gmtime())
    idx = int(hashlib.sha256(seed.encode("utf-8")).hexdigest(), 16) % len(ids)
    return rehydrate(default_corpus().cards[ids[idx]])


def connections(card_id: str, limit: int = 10) -> Optional[Dict[str, Any]]:
    """Cards related to one card — its explicit links plus same-shelf siblings. None if absent."""
    c = get_card(card_id)
    if c is None:
        return None
    shelf = c.get("shelf")
    sibs = [_brief(x) for x in default_corpus().cards.values()
            if x.get("id") != card_id and x.get("shelf") == shelf and is_public(x)][:max(1, min(limit, 50))]
    links = c.get("links") or c.get("connections") or c.get("refs") or []
    return {"id": card_id, "shelf": shelf, "links": links, "same_shelf": sibs}


def locate(q: str, limit: int = 5) -> Dict[str, Any]:
    """Find the card for a query: exact id, then title match, else fall back to ranked search."""
    # found: "q or ''" only substitutes the fallback for a FALSY q — a truthy non-string (an
    # int from an uncoerced MCP tool call arg) survives past that guard and crashes on
    # ".strip()". Matches corpus.search()'s fix, same module.
    q = (str(q) if q else "").strip()
    if not q:
        return {"query": q, "by": "none", "matches": []}
    cards = default_corpus().cards
    if q in cards and is_public(cards[q]):
        return {"query": q, "by": "id", "matches": [_brief(cards[q])]}
    ql = q.lower()
    title_hits = [_brief(c) for c in cards.values() if is_public(c) and ql in (c.get("title") or "").lower()]
    if title_hits:
        return {"query": q, "by": "title", "matches": title_hits[:limit]}
    return {"query": q, "by": "search", "matches": [_brief(c) for c in search(q, limit=limit)]}


def health() -> Dict[str, Any]:
    """Corpus health — is the keeping loaded and sound."""
    cards = [c for c in default_corpus().cards.values() if is_public(c)]
    n = len(cards)
    return {"ok": n > 0, "total": n,
            "with_body": sum(1 for c in cards if (c.get("body") or "").strip()),
            "shelves": len({c.get("shelf") for c in cards}),
            "surfaces": sorted({(c.get("surface") or "?") for c in cards})}
